const BASE: Record<'en' | 'fa' | 'ar', Dict> = { en: EN, fa: FA, ar: AR };
/** Add translations here (partial is fine — missing keys fall back to English). */
export const EXTRA_TRANSLATIONS: Partial<Record<Exclude<A11yLang, 'en' | 'fa' | 'ar'>, Partial<Dict>>> = {};

export function translate(lang: string, key: A11yKey, vars?: Record<string, string | number>): string {
  const l = lang as A11yLang;
  const raw =
    (l === 'en' || l === 'fa' || l === 'ar' ? BASE[l][key] : EXTRA_TRANSLATIONS[l as Exclude<A11yLang, 'en' | 'fa' | 'ar'>]?.[key]) ??
    EN[key];
  return vars ? raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : raw;
}

