/*
# Neutralize the hard-coded demo account (production-safe by default)

## Why
20260821101216_seed_demo_data.sql used to create demo@vireek.com (fixed id a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11)
with a password that was written in the repository. Any project that ran that migration may hold a
known-credential account. This migration closes it, unless the database declares itself a demo/staging one.

## Environment marker (fail-safe: anything unset is treated as production)
    ALTER DATABASE postgres SET app.settings.vireek_environment = 'staging';   -- or 'demo'
Only the values 'demo' and 'staging' skip this migration. See docs/runbooks/demo-account-audit.md.
Check it with:  SHOW app.settings.vireek_environment;   (new sessions only; empty/unset => production)

## What it changes (ONLY the one fixed user id, never by email or pattern)
1. auth.users: banned_until = 'infinity' and the password hash replaced by an unusable value, so the
   known password can never work again even if the ban is lifted later.
2. auth.sessions of that user are deleted (refresh tokens cascade). Already-issued access tokens expire on
   their own (JWT expiry, 1 h by default).
3. profiles.status = 'suspended' (only if it was 'active'), so the account stops counting as a live customer.
4. Seeded demo rows are deleted, matched by their exact fixed ids / exact seed values: 3 jobs, 4 leads,
   6 calls, the seeded technician, the seeded AI insight and the demo Airtable integration. Rows a human
   created later are never matched. Failure of this clean-up only raises a WARNING; steps 1-3 are already done.
The auth user, its profile and business_profile are KEPT (banned) on purpose: deleting auth.users cascades into
tables this migration cannot enumerate safely, and the audit trail stays intact.

## Shape
The logic lives in public.neutralize_demo_account() (callable only by privileged roles) so the guard can be tested
in pgTAP (supabase/tests/database/demo_account_neutralized.test.sql). The migration calls it once. It returns
'skipped:<env>' | 'absent' | 'neutralized' | 'already_neutralized'.

## Idempotent
Re-running is harmless: every statement is conditional and a second run finds nothing left to change.

## Rollback / recovery (manual, deliberate)
-- rollback: UPDATE auth.users SET banned_until = NULL WHERE id = 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11';
--   then set a NEW password through the Supabase dashboard or the admin API (the old password is gone for good),
--   UPDATE profiles SET status = 'active' WHERE id = 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11';
--   and re-create the demo rows ONLY in a demo/staging project with:  DEMO_ENV=staging node scripts/demo/seed.mjs
--   Deleted demo rows are not restored from here; they are regenerated by the seed script. Sessions cannot be restored.
*/

CREATE OR REPLACE FUNCTION public.neutralize_demo_account()
RETURNS text
LANGUAGE plpgsql
SET search_path = public, auth, pg_temp
AS $fn$
DECLARE
  demo_id constant uuid := 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11';
  env text := lower(coalesce(nullif(current_setting('app.settings.vireek_environment', true), ''), ''));
  n integer;
  changed integer;
BEGIN
  IF env IN ('demo', 'staging') THEN
    RETURN 'skipped:' || env;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE id = demo_id) THEN
    RETURN 'absent';
  END IF;

  -- 1) Make sign-in impossible, now and after any future un-ban.
  UPDATE auth.users
     SET banned_until = 'infinity'::timestamptz,
         encrypted_password = '!disabled-' || gen_random_uuid()::text,   -- not a valid bcrypt hash: can never match
         updated_at = now()
   WHERE id = demo_id
     AND (banned_until IS DISTINCT FROM 'infinity'::timestamptz OR coalesce(encrypted_password, '') NOT LIKE '!disabled-%');
  GET DIAGNOSTICS changed = ROW_COUNT;

  -- 2) Kill existing sessions (refresh tokens cascade).
  IF to_regclass('auth.sessions') IS NOT NULL THEN
    DELETE FROM auth.sessions WHERE user_id = demo_id;
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE 'neutralize_demo_account: sessions revoked (rows: %).', n;
  END IF;

  -- 3) Stop counting it as a live customer.
  UPDATE profiles SET status = 'suspended' WHERE id = demo_id AND status = 'active';

  -- 4) Remove only the rows the old seed created, by exact fixed ids / exact seed values.
  BEGIN
    DELETE FROM jobs WHERE user_id = demo_id AND id IN (
      'd1eebc99-9c0b-4ef8-bb6d-6bb9bd380a01', 'd1eebc99-9c0b-4ef8-bb6d-6bb9bd380a02', 'd1eebc99-9c0b-4ef8-bb6d-6bb9bd380a03');
    DELETE FROM leads WHERE user_id = demo_id AND id IN (
      'c1eebc99-9c0b-4ef8-bb6d-6bb9bd380a01', 'c1eebc99-9c0b-4ef8-bb6d-6bb9bd380a02',
      'c1eebc99-9c0b-4ef8-bb6d-6bb9bd380a03', 'c1eebc99-9c0b-4ef8-bb6d-6bb9bd380a04');
    DELETE FROM calls WHERE user_id = demo_id AND id IN (
      'b1eebc99-9c0b-4ef8-bb6d-6bb9bd380a01', 'b1eebc99-9c0b-4ef8-bb6d-6bb9bd380a02', 'b1eebc99-9c0b-4ef8-bb6d-6bb9bd380a03',
      'b1eebc99-9c0b-4ef8-bb6d-6bb9bd380a04', 'b1eebc99-9c0b-4ef8-bb6d-6bb9bd380a05', 'b1eebc99-9c0b-4ef8-bb6d-6bb9bd380a06');
    DELETE FROM team_members WHERE account_owner_id = demo_id AND member_email = 'james@bluepipe.example';
    DELETE FROM ai_insights WHERE user_id = demo_id AND title = 'After-hours calls trending up';
    DELETE FROM integrations WHERE user_id = demo_id AND integration_type = 'airtable' AND config ->> 'base_id' = 'appXX_demo_base';
  EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'neutralize_demo_account: demo data clean-up skipped (%). The account itself is already disabled.', SQLERRM;
  END;

  RETURN CASE WHEN changed > 0 THEN 'neutralized' ELSE 'already_neutralized' END;
END
$fn$;

COMMENT ON FUNCTION public.neutralize_demo_account() IS
  'Disables the legacy hard-coded demo user (fixed id) unless app.settings.vireek_environment is demo/staging. Idempotent. Privileged callers only.';

REVOKE ALL ON FUNCTION public.neutralize_demo_account() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.neutralize_demo_account() FROM anon, authenticated;

DO $$
DECLARE
  result text := public.neutralize_demo_account();
BEGIN
  RAISE NOTICE 'neutralize_demo_account: %', result;
END
$$;
