/*
  # Dispute-ratio monitoring (per tenant + platform)

  ## Inputs (verified in the repo)
  - stripe_disputes (20270510000000_stripe_disputes.sql): written only by apply_stripe_dispute_event()
    from the stripe-dispute-webhook edge function. Numerator = disputes OPENED in the month (UTC).
  - payment_requests: status = 'paid' with paid_at. Denominator = paid, non-bank payments in the month (UTC).
    Bank-rail payments (payment_rail = 'bank') are excluded because card disputes do not apply to them.

  ## Known limitation  [VERIFY]
  Only payment_requests rows are counted as transactions. If card payments are also recorded in other tables
  (e.g. in-person or plan installments) the denominator is understated and the ratio overstated. Extend the
  `t` CTE in dispute_ratio_monthly_v once those sources are confirmed.

  ## Thresholds  [VERIFY against payment provider docs]
  The seeded numbers are INTERNAL early-warning placeholders, NOT provider or card-network limits.
  They ship with verified = false. Confirm the provider's definition of "dispute rate" and its published
  limits, then change them through set_dispute_ratio_thresholds() (staff only).

  ## Security
  - dispute_ratio_monthly_v is security_invoker: tenants only ever see their own rows (RLS on stripe_disputes
    and payment_requests, which also requires billing permission via can_access_disputes()).
  - Platform numbers are reachable only through dispute_ratio_platform_monthly() (staff check inside).
  - Alerts are generated by dispute_ratio_check_alerts() (service role / pg_cron only), deduplicated by
    UNIQUE (scope_key, month, level) so reruns never notify twice.
*/

-- ---------------------------------------------------------------------------
-- 1. Thresholds (configurable)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.dispute_ratio_thresholds (
  scope text PRIMARY KEY CHECK (scope IN ('tenant_default', 'platform')),
  warning_pct numeric(6, 3) NOT NULL CHECK (warning_pct >= 0 AND warning_pct <= 100),
  critical_pct numeric(6, 3) NOT NULL CHECK (critical_pct >= 0 AND critical_pct <= 100),
  min_transactions integer NOT NULL CHECK (min_transactions BETWEEN 1 AND 1000000),
  verified boolean NOT NULL DEFAULT false,
  note text NOT NULL DEFAULT '[VERIFY against payment provider docs]',
  updated_by uuid,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT drt_critical_gte_warning CHECK (critical_pct >= warning_pct)
);

INSERT INTO public.dispute_ratio_thresholds (scope, warning_pct, critical_pct, min_transactions) VALUES
  ('tenant_default', 0.500, 0.750, 20),
  ('platform',       0.500, 0.750, 200)
ON CONFLICT (scope) DO NOTHING;

ALTER TABLE public.dispute_ratio_thresholds ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "select_dispute_ratio_thresholds" ON public.dispute_ratio_thresholds;
CREATE POLICY "select_dispute_ratio_thresholds" ON public.dispute_ratio_thresholds FOR SELECT TO authenticated USING (true);
REVOKE ALL ON public.dispute_ratio_thresholds FROM anon, authenticated;
GRANT SELECT ON public.dispute_ratio_thresholds TO authenticated;

COMMENT ON TABLE public.dispute_ratio_thresholds IS
  'Internal early-warning thresholds for the dispute ratio. Placeholders, not provider limits. [VERIFY against payment provider docs]';

-- ---------------------------------------------------------------------------
-- 2. Pure classifier (shared by the view, the platform RPC and the alert job)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.dispute_ratio_level(
  p_disputes integer,
  p_transactions integer,
  p_warning_pct numeric,
  p_critical_pct numeric,
  p_min_transactions integer
)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public
AS $$
  SELECT CASE
    WHEN p_transactions IS NULL OR p_transactions < GREATEST(p_min_transactions, 1) THEN 'insufficient_data'
    WHEN 100.0 * COALESCE(p_disputes, 0) / p_transactions >= p_critical_pct THEN 'critical'
    WHEN 100.0 * COALESCE(p_disputes, 0) / p_transactions >= p_warning_pct THEN 'warning'
    ELSE 'ok'
  END;
$$;

-- ---------------------------------------------------------------------------
-- 3. Index for the denominator scan
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_payment_requests_paid_month
  ON public.payment_requests (user_id, paid_at)
  WHERE status = 'paid' AND paid_at IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 4. Monthly ratio per tenant (security_invoker: caller's RLS applies)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.dispute_ratio_monthly_v WITH (security_invoker = true) AS
WITH d AS (
  SELECT user_id,
         (date_trunc('month', timezone('UTC', opened_at)))::date AS month,
         count(*)::integer AS disputes_count
  FROM public.stripe_disputes
  GROUP BY 1, 2
),
t AS (
  SELECT user_id,
         (date_trunc('month', timezone('UTC', paid_at)))::date AS month,
         count(*)::integer AS txn_count
  FROM public.payment_requests
  WHERE status = 'paid' AND paid_at IS NOT NULL AND COALESCE(payment_rail, 'card') <> 'bank'
  GROUP BY 1, 2
),
m AS (
  SELECT COALESCE(d.user_id, t.user_id) AS user_id,
         COALESCE(d.month, t.month)     AS month,
         COALESCE(d.disputes_count, 0)  AS disputes_count,
         COALESCE(t.txn_count, 0)       AS txn_count
  FROM d FULL JOIN t ON d.user_id = t.user_id AND d.month = t.month
),
c AS (
  SELECT warning_pct, critical_pct, min_transactions
  FROM public.dispute_ratio_thresholds
  WHERE scope = 'tenant_default'
)
SELECT
  m.user_id,
  m.month,
  m.disputes_count,
  m.txn_count,
  CASE WHEN m.txn_count > 0 THEN round(100.0 * m.disputes_count / m.txn_count, 3) END AS ratio_pct,
  public.dispute_ratio_level(m.disputes_count, m.txn_count, c.warning_pct, c.critical_pct, c.min_transactions) AS level,
  c.warning_pct,
  c.critical_pct,
  c.min_transactions
FROM m CROSS JOIN c;

REVOKE ALL ON public.dispute_ratio_monthly_v FROM PUBLIC, anon;
GRANT SELECT ON public.dispute_ratio_monthly_v TO authenticated;

COMMENT ON VIEW public.dispute_ratio_monthly_v IS
  'Disputes opened / paid non-bank payments per tenant and UTC month. Level uses internal placeholder thresholds. [VERIFY against payment provider docs]';

-- ---------------------------------------------------------------------------
-- 5. Platform aggregate (staff only)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.dispute_ratio_platform_monthly(p_months integer DEFAULT 12)
RETURNS TABLE (
  month date,
  disputes_count integer,
  txn_count integer,
  ratio_pct numeric,
  level text,
  tenants_with_disputes integer,
  tenants_warning integer,
  tenants_critical integer,
  warning_pct numeric,
  critical_pct numeric,
  thresholds_verified boolean,
  min_transactions integer
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
#variable_conflict use_column
DECLARE
  v_from date := (date_trunc('month', timezone('UTC', now()))::date - make_interval(months => LEAST(GREATEST(COALESCE(p_months, 12), 1), 36) - 1))::date;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (SELECT 1 FROM public.profiles pr WHERE pr.id = auth.uid() AND pr.is_staff) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT
    v.month,
    sum(v.disputes_count)::integer,
    sum(v.txn_count)::integer,
    CASE WHEN sum(v.txn_count) > 0 THEN round(100.0 * sum(v.disputes_count) / sum(v.txn_count), 3) END,
    public.dispute_ratio_level(sum(v.disputes_count)::integer, sum(v.txn_count)::integer, th.warning_pct, th.critical_pct, th.min_transactions),
    (count(*) FILTER (WHERE v.disputes_count > 0))::integer,
    (count(*) FILTER (WHERE v.level = 'warning'))::integer,
    (count(*) FILTER (WHERE v.level = 'critical'))::integer,
    th.warning_pct,
    th.critical_pct,
    th.verified,
    th.min_transactions
  FROM public.dispute_ratio_monthly_v v
  CROSS JOIN (SELECT * FROM public.dispute_ratio_thresholds WHERE scope = 'platform') th
  WHERE v.month >= v_from
  GROUP BY v.month, th.warning_pct, th.critical_pct, th.min_transactions, th.verified
  ORDER BY v.month DESC;
END;
$$;
REVOKE ALL ON FUNCTION public.dispute_ratio_platform_monthly(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.dispute_ratio_platform_monthly(integer) TO authenticated;

-- ---------------------------------------------------------------------------
-- 6. Threshold writer (staff only)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_dispute_ratio_thresholds(
  p_scope text,
  p_warning_pct numeric,
  p_critical_pct numeric,
  p_min_transactions integer,
  p_verified boolean DEFAULT false
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (SELECT 1 FROM public.profiles pr WHERE pr.id = auth.uid() AND pr.is_staff) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;
  IF p_scope NOT IN ('tenant_default', 'platform') THEN
    RAISE EXCEPTION 'invalid_scope' USING ERRCODE = '22023';
  END IF;
  IF p_warning_pct IS NULL OR p_critical_pct IS NULL OR p_warning_pct < 0 OR p_critical_pct > 100 OR p_critical_pct < p_warning_pct THEN
    RAISE EXCEPTION 'invalid_thresholds' USING ERRCODE = '22023';
  END IF;
  IF p_min_transactions IS NULL OR p_min_transactions < 1 OR p_min_transactions > 1000000 THEN
    RAISE EXCEPTION 'invalid_min_transactions' USING ERRCODE = '22023';
  END IF;

  UPDATE public.dispute_ratio_thresholds
     SET warning_pct = p_warning_pct,
         critical_pct = p_critical_pct,
         min_transactions = p_min_transactions,
         verified = COALESCE(p_verified, false),
         updated_by = auth.uid(),
         updated_at = now()
   WHERE scope = p_scope;
END;
$$;
REVOKE ALL ON FUNCTION public.set_dispute_ratio_thresholds(text, numeric, numeric, integer, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_dispute_ratio_thresholds(text, numeric, numeric, integer, boolean) TO authenticated;

-- ---------------------------------------------------------------------------
-- 7. Alerts (deduplicated)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.dispute_ratio_alerts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  scope_key text NOT NULL,                       -- 'platform' or 'tenant:<uuid>'
  month date NOT NULL,
  level text NOT NULL CHECK (level IN ('warning', 'critical')),
  disputes_count integer NOT NULL,
  txn_count integer NOT NULL,
  ratio_pct numeric(8, 3),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (scope_key, month, level)
);
ALTER TABLE public.dispute_ratio_alerts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.dispute_ratio_alerts FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.dispute_ratio_check_alerts()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cur date := date_trunc('month', timezone('UTC', now()))::date;
  v_prev date := (date_trunc('month', timezone('UTC', now()))::date - interval '1 month')::date;
  r record;
  v_rows bigint;
  v_tenant_alerts integer := 0;
  v_platform_alerts integer := 0;
BEGIN
  -- Tenants
  FOR r IN
    SELECT v.user_id, v.month, v.level, v.disputes_count, v.txn_count, v.ratio_pct
    FROM public.dispute_ratio_monthly_v v
    WHERE v.month IN (v_cur, v_prev) AND v.level IN ('warning', 'critical')
  LOOP
    INSERT INTO public.dispute_ratio_alerts (scope_key, month, level, disputes_count, txn_count, ratio_pct)
    VALUES ('tenant:' || r.user_id::text, r.month, r.level, r.disputes_count, r.txn_count, r.ratio_pct)
    ON CONFLICT (scope_key, month, level) DO NOTHING;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows > 0 THEN
      INSERT INTO public.notifications (user_id, type, title, message, action_url)
      VALUES (
        r.user_id, 'system',
        CASE WHEN r.level = 'critical' THEN 'Dispute ratio is high' ELSE 'Dispute ratio is rising' END,
        format('%s of %s card payments in %s were disputed (%s%%). Review open disputes and send evidence on time.',
               r.disputes_count, r.txn_count, to_char(r.month, 'YYYY-MM'), to_char(r.ratio_pct, 'FM990.00')),
        '/dashboard/disputes'
      );
      v_tenant_alerts := v_tenant_alerts + 1;
    END IF;
  END LOOP;

  -- Platform
  FOR r IN
    SELECT p.month,
           sum(p.disputes_count)::integer AS disputes_count,
           sum(p.txn_count)::integer AS txn_count,
           round(100.0 * sum(p.disputes_count) / NULLIF(sum(p.txn_count), 0), 3) AS ratio_pct,
           public.dispute_ratio_level(sum(p.disputes_count)::integer, sum(p.txn_count)::integer, th.warning_pct, th.critical_pct, th.min_transactions) AS level
    FROM public.dispute_ratio_monthly_v p
    CROSS JOIN (SELECT * FROM public.dispute_ratio_thresholds WHERE scope = 'platform') th
    WHERE p.month IN (v_cur, v_prev)
    GROUP BY p.month, th.warning_pct, th.critical_pct, th.min_transactions
  LOOP
    CONTINUE WHEN r.level NOT IN ('warning', 'critical');
    INSERT INTO public.dispute_ratio_alerts (scope_key, month, level, disputes_count, txn_count, ratio_pct)
    VALUES ('platform', r.month, r.level, r.disputes_count, r.txn_count, r.ratio_pct)
    ON CONFLICT (scope_key, month, level) DO NOTHING;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows > 0 THEN
      INSERT INTO public.notifications (user_id, type, title, message, action_url)
      SELECT pr.id, 'system',
             CASE WHEN r.level = 'critical' THEN 'Platform dispute ratio is high' ELSE 'Platform dispute ratio is rising' END,
             format('Platform ratio for %s: %s of %s card payments (%s%%).',
                    to_char(r.month, 'YYYY-MM'), r.disputes_count, r.txn_count, to_char(r.ratio_pct, 'FM990.00')),
             '/staff/dispute-ratio'
      FROM public.profiles pr WHERE pr.is_staff;
      v_platform_alerts := v_platform_alerts + 1;
    END IF;
  END LOOP;

  RETURN jsonb_build_object('tenant_alerts', v_tenant_alerts, 'platform_alerts', v_platform_alerts);
END;
$$;
REVOKE ALL ON FUNCTION public.dispute_ratio_check_alerts() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.dispute_ratio_check_alerts() TO service_role;

