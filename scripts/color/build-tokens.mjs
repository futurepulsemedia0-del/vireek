#!/usr/bin/env node
// scripts/color/build-tokens.mjs — `npm run tokens:build`
// Generates (never hand-edit the outputs):
//   src/styles/tokens.generated.css      CSS variables for light / dark / high-contrast / forced-colors
//   src/styles/tokens.generated.ts       HEX constants (canvas, charts, native status bar, theme-color meta)
//   supabase/functions/_shared/brand-colors.ts   same constants for Deno edge functions (emails, PDFs)
//   docs/design/COLOR_TOKENS.md          token table with MEASURED contrast ratios + before/after
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildTheme, declaredPairs, THEMES, MESH_ALPHA, FAMILY_NAMES, FAMILY_DEFS, buildScale, NEUTRAL_SCALE } from './palette.mjs';
import { toHex, contrast, simulate, deltaE } from './oklch.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = (rel, text) => { const p = join(ROOT, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); };
const triplet = (rgb) => rgb.join(' ');
const themes = Object.fromEntries(THEMES.map((t) => [t, buildTheme(t)]));

// ------------------------------------------------------------------ CSS
const block = (sel, t, extra = '') => `${sel} {\n${Object.entries(themes[t].tok).map(([k, v]) => `  --${k}: ${triplet(v)};`).join('\n')}\n  --glass-alpha: ${themes[t].meta.glassAlpha};\n${extra}}\n`;
const css = `/* GENERATED by scripts/color/build-tokens.mjs from scripts/color/palette.mjs — DO NOT EDIT.
   Run \`npm run tokens:build\`. Values are space-separated RGB triplets (use rgb(var(--x) / alpha)). */

${block(':root', 'light', '  color-scheme: light;\n')}
${block('.dark,\n.a11y-dark-contrast', 'dark', '  color-scheme: dark;\n')}
/* Accessibility Center "light contrast" must win even when .dark is present (declared after .dark). */
${block('.a11y-light-contrast', 'light', '  color-scheme: light;\n')}
/* Strong tokens: OS-level "more contrast" (default theme + manual .dark override) */
@media (prefers-contrast: more) {
${block('  :root', 'light-hc').replace(/^/gm, '').split('\n').map((l) => (l ? '  ' + l : l)).join('\n')}
${block('  .dark,\n  .a11y-dark-contrast', 'dark-hc').split('\n').map((l) => (l ? '  ' + l : l)).join('\n')}
}
/* Accessibility Center "high contrast" toggle */
${block('.a11y-high-contrast', 'light-hc')}
${block('.a11y-high-contrast.dark,\n.a11y-high-contrast.a11y-dark-contrast', 'dark-hc')}
/* Brand radial wash peak alphas (solver-verified in palette.mjs) */
:root { --mesh-accent-alpha: ${MESH_ALPHA.accent}; --mesh-cta-alpha: ${MESH_ALPHA.cta}; }

::selection { background-color: rgb(var(--selection-bg)); color: rgb(var(--selection-fg)); }

/* Non-colour cues (WCAG 1.4.1): inline links underlined; disabled controls get cursor + dashed border */
p a, .prose a { text-decoration-line: underline; text-decoration-thickness: 1px; text-underline-offset: 3px; }
button:disabled, [aria-disabled='true'] { cursor: not-allowed; }
input:disabled, select:disabled, textarea:disabled { border-style: dashed; cursor: not-allowed; background-color: rgb(var(--disabled-bg)); color: rgb(var(--disabled-fg)); }

/* Windows High Contrast / forced-colors: use system colours, keep focus + boundaries visible */
@media (forced-colors: active) {
  :focus-visible { outline: 2px solid Highlight !important; outline-offset: 2px; }
  button, [role='button'], input, select, textarea { outline: 1px solid ButtonText; outline-offset: -1px; }
  .focus-ring:focus-visible { box-shadow: none; }
  [aria-selected='true'], [aria-current], [aria-pressed='true'], [aria-checked='true'] { outline: 2px solid Highlight; }
  .bg-gradient-mesh { background-image: none; }
}
`;
out('src/styles/tokens.generated.css', css);

// ------------------------------------------------------------------ TS / Deno constants
const hexMap = (t) => Object.fromEntries(Object.entries(themes[t].tok).map(([k, v]) => [k, toHex(v)]));
const ts = `// GENERATED by scripts/color/build-tokens.mjs — DO NOT EDIT. Run \`npm run tokens:build\`.
// Use ONLY where CSS variables cannot reach (canvas, native status bar, theme-color meta, emails, PDFs).
export const BRAND_COLORS = ${JSON.stringify({ light: hexMap('light'), dark: hexMap('dark') }, null, 2)} as const;
export const THEME_COLOR = { light: '${toHex(themes.light.tok['bg-primary'])}', dark: '${toHex(themes.dark.tok['bg-primary'])}' } as const;
export const VIZ_PATTERNS = ['solid', 'diagonal', 'dots', 'cross', 'horizontal', 'vertical', 'checker', 'zigzag'] as const;
export const VIZ_MARKERS = ['circle', 'square', 'triangle', 'diamond', 'cross', 'star', 'hexagon', 'plus'] as const;
`;
out('src/styles/tokens.generated.ts', ts);
out('supabase/functions/_shared/brand-colors.ts', ts);

// ------------------------------------------------------------------ docs table
const LEGACY = { // measured on the previous system (for the before/after table)
  light: { bg: [253, 252, 250], items: { 'copper text': [214, 88, 42], 'white on copper fill': [255, 255, 255, [214, 88, 42]], 'success text (on bg-tertiary)': [22, 132, 88, [246, 244, 240]], 'border default': [231, 229, 224], 'text-secondary (on bg-tertiary)': [103, 103, 112, [246, 244, 240]] } },
  dark: { bg: [9, 10, 13], items: { 'white on accent fill': [255, 255, 255, [108, 130, 255]], 'border default': [36, 37, 44] } },
};
const row = (c) => c.toFixed(2).padStart(5) + ':1';
let md = `# Vireek colour tokens\n\n> GENERATED by \`npm run tokens:build\` from \`scripts/color/palette.mjs\` (OKLCH source of truth). Do not edit.\n\n`;
md += `## Before / after (measured, WCAG 2.x relative luminance)\n\n| Pair | Before | After | Requirement |\n|---|---|---|---|\n`;
const L = themes.light.tok, D = themes.dark.tok;
const bgL = L['bg-primary'], bgL3 = L['bg-tertiary'];
const legacyRows = [
  ['Light — copper as TEXT on bg-primary', contrast([214, 88, 42], LEGACY.light.bg), contrast(L['cta-text'], bgL), '≥ 4.5'],
  ['Light — white text on copper FILL', contrast([255, 255, 255], [214, 88, 42]), contrast(L['on-cta'], L['cta-fill']), '≥ 4.5'],
  ['Light — copper graphic on bg-tertiary', contrast([214, 88, 42], [246, 244, 240]), contrast(L['cta-graphic'], bgL3), '≥ 3'],
  ['Light — success text on bg-tertiary', contrast([22, 132, 88], [246, 244, 240]), contrast(L['success-text'], bgL3), '≥ 4.5'],
  ['Light — text-secondary on bg-tertiary', contrast([103, 103, 112], [246, 244, 240]), contrast(L['text-secondary'], bgL3), '≥ 4.5'],
  ['Light — control border vs bg-secondary', contrast([231, 229, 224], [255, 255, 255]), contrast(L['border-strong'], L['bg-secondary']), '≥ 3 (1.4.11)'],
  ['Dark — white text on accent fill', contrast([255, 255, 255], [108, 130, 255]), contrast(D['on-accent'], D['accent-fill']), '≥ 4.5'],
  ['Dark — control border vs bg-secondary', contrast([36, 37, 44], [16, 17, 21]), contrast(D['border-strong'], D['bg-secondary']), '≥ 3 (1.4.11)'],
];
for (const [n, b, a, r] of legacyRows) md += `| ${n} | ${row(b)} ${b < parseFloat(r.replace(/[^0-9.]/g, '')) ? '❌' : '✅'} | ${row(a)} ✅ | ${r} |\n`;
md += `\n## Tokens (RGB hex per theme)\n\n| Token | Light | Dark | Light-HC | Dark-HC |\n|---|---|---|---|---|\n`;
for (const k of Object.keys(themes.light.tok)) md += `| \`${k}\` | ${THEMES.map((t) => '`' + toHex(themes[t].tok[k]) + '`').join(' | ')} |\n`;
md += `\n## Every declared pair (CI-enforced)\n`;
for (const t of THEMES) {
  const P = declaredPairs(t);
  md += `\n### ${t} — ${P.length} pairs, min ratio ${Math.min(...P.map((p) => contrast(p.fgRgb, p.bgRgb))).toFixed(2)}\n\n| Foreground | Background | Ratio | Min | Use |\n|---|---|---|---|---|\n`;
  for (const p of P) { const c = contrast(p.fgRgb, p.bgRgb); md += `| \`${p.fg}\` | \`${p.bg}\` | ${c.toFixed(2)} | ${p.min} | ${p.label} |\n`; }
}
md += `\n## Data-viz colour-blind check (min pairwise OKLab ΔE across 8 categorical series)\n\n| Theme | Normal | Protanopia | Deuteranopia | Tritanopia | Grayscale |\n|---|---|---|---|---|---|\n`;
for (const t of ['light', 'dark']) {
  const cols = [...Array(8)].map((_, i) => themes[t].tok[`viz-${i + 1}`]);
  const minD = (kind) => { const s = kind ? cols.map((c) => simulate(c, kind)) : cols; let m = 9; for (let i = 0; i < 8; i++) for (let j = i + 1; j < 8; j++) m = Math.min(m, deltaE(s[i], s[j])); return m.toFixed(3); };
  md += `| ${t} | ${minD()} | ${minD('protanopia')} | ${minD('deuteranopia')} | ${minD('tritanopia')} | ${minD('grayscale')} |\n`;
}
md += `\nΔE < ~0.08 means two series can be confused by colour alone — which is why every series also carries a pattern (\`VIZ_PATTERNS\`), a marker shape (\`VIZ_MARKERS\`) and a direct label.\n`;
out('docs/design/COLOR_TOKENS.md', md);
console.log('✔ tokens generated:', ['src/styles/tokens.generated.css', 'src/styles/tokens.generated.ts', 'supabase/functions/_shared/brand-colors.ts', 'docs/design/COLOR_TOKENS.md'].join(', '));
