#!/usr/bin/env node
// scripts/color/export-tokens.mjs — design hand-off artefacts, generated from palette.mjs (never edit the outputs by hand).
//   docs/design/tokens.json         W3C Design-Tokens format (Figma Tokens Studio / Style Dictionary compatible), 4 themes + scales + viz
//   docs/design/color-preview.html  self-contained page: both themes side by side, real components, contrast table
// Run: node scripts/color/export-tokens.mjs        (also wired as `npm run tokens:export`)
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, buildTheme, FAMILY_NAMES, FAMILY_DEFS, buildScale, NEUTRAL_SCALE } from './palette.mjs';
import { toHex, contrast } from './oklch.mjs';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..');
const OUT = join(ROOT, 'docs', 'design');
mkdirSync(OUT, { recursive: true });

const T = Object.fromEntries(THEMES.map((t) => [t, buildTheme(t).tok]));
const hex = (t, k) => toHex(T[t][k]);

// ---------------- tokens.json (DTCG)
const tok = (v, d) => ({ $value: v, $type: 'color', ...(d ? { $description: d } : {}) });
const json = { $description: 'Vireek colour tokens — generated by scripts/color/export-tokens.mjs from palette.mjs. Do not edit.', theme: {}, scale: {}, dataviz: {} };
for (const t of THEMES) json.theme[t] = Object.fromEntries(Object.keys(T[t]).filter((k) => !/^viz-/.test(k)).map((k) => [k, tok(hex(t, k))]));
for (const n of FAMILY_NAMES) json.scale[n] = Object.fromEntries(Object.entries(buildScale({ ...FAMILY_DEFS[n] })).map(([s, h]) => [s, tok(h)]));
json.scale.graphite = Object.fromEntries(Object.entries(NEUTRAL_SCALE).map(([s, h]) => [s, tok(h)]));
for (const t of ['light', 'dark']) json.dataviz[t] = Object.fromEntries(Object.keys(T[t]).filter((k) => /^viz-/.test(k)).map((k) => [k, tok(hex(t, k))]));
writeFileSync(join(OUT, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');

// ---------------- color-preview.html
const vars = (t) => Object.keys(T[t]).map((k) => `--${k}:${hex(t, k)};`).join('');
const FAM = ['accent', 'cta', 'success', 'danger', 'warning', 'info'];
const pairRows = (t) => FAM.flatMap((f) => [[`on-${f}`, `${f}-fill`], [`${f}-text`, 'bg-primary'], [`${f}-strong`, `${f}-subtle`]]).map(([a, b]) => ({ a, b, cr: contrast(T[t][a], T[t][b]) }));
const panel = (t) => `
<section class="panel" data-theme="${t}" style="${vars(t)}">
  <h2>${t}</h2>
  <p class="muted">Muted text · <span style="color:var(--text-secondary)">secondary</span> · <a href="#" style="color:var(--accent-text)">link (accent-text)</a></p>
  <div class="row">${FAM.map((f) => `<button style="background:var(--${f}-fill);color:var(--on-${f})">${f}</button>`).join('')}</div>
  <div class="row">${FAM.map((f) => `<span class="alert" style="background:var(--${f}-subtle);border-color:var(--${f}-subtle-border);color:var(--${f}-strong)"><i style="background:var(--${f}-graphic)"></i>${f}</span>`).join('')}</div>
  <div class="card"><b>Card</b> on <code>bg-secondary</code><div class="bars">${[1, 2, 3, 4, 5, 6, 7, 8].map((i) => `<s style="background:var(--viz-${i});height:${30 + ((i * 37) % 60)}px"></s>`).join('')}</div>
  <div class="seq">${[1, 2, 3, 4, 5, 6, 7, 8, 9].map((i) => `<s style="background:var(--viz-seq-${i})"></s>`).join('')}</div>
  <div class="seq">${[1, 2, 3, 4, 5, 6, 7, 8, 9].map((i) => `<s style="background:var(--viz-div-${i})"></s>`).join('')}</div></div>
  <table>${pairRows(t).map((r) => `<tr><td>${r.a} on ${r.b}</td><td>${r.cr.toFixed(2)}:1</td><td>${r.cr >= 4.5 ? 'AA' : r.cr >= 3 ? 'large/graphic' : 'FAIL'}</td></tr>`).join('')}</table>
</section>`;
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Vireek colour system — preview</title>
<style>body{margin:0;font:14px/1.5 system-ui,sans-serif;display:grid;grid-template-columns:repeat(auto-fit,minmax(360px,1fr))}
.panel{background:var(--bg-primary);color:var(--text-primary);padding:24px}.panel h2{margin:0 0 8px;text-transform:uppercase;letter-spacing:.08em;font-size:12px;color:var(--text-secondary)}
.muted{color:var(--text-muted)}.row{display:flex;flex-wrap:wrap;gap:8px;margin:12px 0}button{border:0;border-radius:8px;padding:8px 14px;font:inherit;font-weight:600}
.alert{display:inline-flex;align-items:center;gap:6px;border:1px solid;border-radius:8px;padding:4px 10px}.alert i{width:8px;height:8px;border-radius:50%}
.card{background:var(--bg-secondary);border:1px solid var(--border-default);border-radius:12px;padding:14px;margin:12px 0}.bars{display:flex;gap:6px;align-items:flex-end;height:90px;margin:12px 0}.bars s{flex:1;border-radius:4px 4px 0 0}
.seq{display:flex;height:14px;margin-top:6px}.seq s{flex:1}table{width:100%;border-collapse:collapse;font-size:12px}td{border-top:1px solid var(--border-default);padding:3px 6px}code{background:var(--bg-tertiary);padding:1px 5px;border-radius:4px}</style></head>
<body>${['light', 'dark', 'light-hc', 'dark-hc'].map(panel).join('')}</body></html>`;
writeFileSync(join(OUT, 'color-preview.html'), html);
console.log(`✔ docs/design/tokens.json (${Object.keys(json.theme.light).length} tokens × ${THEMES.length} themes) and docs/design/color-preview.html`);
