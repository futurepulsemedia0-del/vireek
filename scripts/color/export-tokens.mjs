#!/usr/bin/env node
// scripts/color/export-tokens.mjs — writes docs/design/tokens.json (W3C design-token format) from palette.mjs.
//   node scripts/color/export-tokens.mjs            write the file
//   node scripts/color/export-tokens.mjs --check    exit 1 if the file on disk differs from what palette.mjs produces
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, buildTheme, FAMILY_NAMES, FAMILY_DEFS, buildScale, NEUTRAL_SCALE } from './palette.mjs';
import { toHex } from './oklch.mjs';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..');
const OUT = join(ROOT, 'docs', 'design', 'tokens.json');
const color = (hex) => ({ $value: hex, $type: 'color' });
const isRgb = (v) => Array.isArray(v) && v.length === 3 && v.every((n) => Number.isFinite(n));

const theme = {};
for (const t of THEMES) {
  theme[t] = {};
  for (const [k, v] of Object.entries(buildTheme(t).tok)) if (isRgb(v) && !k.startsWith('viz-')) theme[t][k] = color(toHex(v));
}
const scale = {};
for (const f of FAMILY_NAMES) scale[f] = Object.fromEntries(Object.entries(buildScale({ ...FAMILY_DEFS[f] })).map(([s, h]) => [s, color(h.toUpperCase())]));
scale.graphite = Object.fromEntries(Object.entries(NEUTRAL_SCALE).map(([s, h]) => [s, color(h.toUpperCase())]));
const dataviz = {};
for (const t of ['light', 'dark']) {
  dataviz[t] = {};
  for (const [k, v] of Object.entries(buildTheme(t).tok)) if (k.startsWith('viz-') && isRgb(v)) dataviz[t][k] = color(toHex(v));
}
const text = JSON.stringify({ $description: 'Vireek colour tokens — generated by scripts/color/export-tokens.mjs from palette.mjs. Do not edit.', theme, scale, dataviz }, null, 2) + '\n';

if (process.argv.includes('--check')) {
  let disk = ''; try { disk = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (disk !== text) { console.error('✘ docs/design/tokens.json is out of date — run: node scripts/color/export-tokens.mjs'); process.exit(1); }
  console.log('✔ docs/design/tokens.json is in sync with palette.mjs'); process.exit(0);
}
writeFileSync(OUT, text);
console.log('✔ wrote docs/design/tokens.json');
