#!/usr/bin/env node
// scripts/gen-docs-catalogs.mjs
//
// Generates the code-derived catalogs that complement `npm run docs:inventory`:
//
//   docs/generated/ROUTES.md        every <Route path> -> page -> guard (App.tsx + src/routes/groups/*)
//   docs/generated/WEBHOOKS.md      inbound webhook / callback / ingest functions + detected controls
//   docs/generated/CRON_CATALOG.md  every cron.schedule(...) in supabase/migrations (active vs commented-out)
//   docs/generated/SCRIPTS.md       every package.json script + description taken from its script header
//   docs/generated/INTEGRATIONS.md  third-party providers referenced in code + docs that mention them
//
// Static scan only (regex). It is an inventory, not proof: every "detected" column says what the
// source text contains, nothing more. Plain Node, no dependencies.
//
// Usage:  npm run docs:catalogs
//         npm run docs:catalogs -- --check     exit 1 if committed files are stale

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const CHECK = process.argv.includes('--check')
const OUT = 'docs/generated'
const read = (p) => readFileSync(p, 'utf8')
const walk = (d) =>
  !existsSync(d)
    ? []
    : readdirSync(d).flatMap((n) => {
        const p = join(d, n)
        return statSync(p).isDirectory() ? (n === 'node_modules' || n === 'dist' ? [] : walk(p)) : [p]
      })
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
const code = (xs) => (xs.length ? xs.map((x) => `\`${esc(x)}\``).join(', ') : '—')
const header = (title, how) =>
  `# ${title}\n\n> Generated by \`npm run docs:catalogs\` — do not edit by hand.\n> ${how}\n\n`
const files = new Map()

// ---------------------------------------------------------------- routes
{
  const GUARDS = ['ProtectedRoute', 'StaffRoute', 'TechnicianRoute', 'PartnerRoute']
  const sources = [
    'src/App.tsx',
    ...walk('src/routes/groups').filter((f) => /Routes\.tsx$/.test(f)),
  ].filter(existsSync)
  const rows = []
  for (const f of sources) {
    const chunks = read(f).split(/<Route\b/).slice(1)
    for (const c of chunks) {
      const head = c.slice(0, 900)
      const m = head.match(/\bpath=(?:"([^"]+)"|\{'([^']+)'\}|\{ROUTES\.([A-Za-z0-9_]+)\})/)
      if (!m) continue
      const path = m[1] ?? m[2] ?? `ROUTES.${m[3]}`
      const guards = GUARDS.filter((g) => new RegExp(`<${g}\\b`).test(head))
      const el = head.match(/element=\{[\s\S]*?<([A-Z][A-Za-z0-9]*)\b(?![^>]*Route)/g) ?? []
      const comps = [...head.matchAll(/<([A-Z][A-Za-z0-9]*)\b/g)]
        .map((x) => x[1])
        .filter((x) => !GUARDS.includes(x) && !['Route', 'Suspense', 'Navigate', 'Outlet'].includes(x))
      rows.push({ path, page: comps[0] ?? (/Navigate/.test(head) ? '(redirect)' : '—'), guards, file: f, el: el.length })
    }
  }
  const area = (p) => (p.startsWith('/dashboard') ? 'dashboard' : p.startsWith('/staff') ? 'staff' : p.startsWith('/tech') ? 'tech' : p.startsWith('/portal') || p.startsWith('/p/') ? 'portal' : 'public/other')
  rows.sort((a, b) => area(a.path).localeCompare(area(b.path)) || a.path.localeCompare(b.path))
  const unguarded = rows.filter((r) => !r.guards.length && ['dashboard', 'staff', 'tech'].includes(area(r.path)))
  let md =
    header('Route map', 'Source: `<Route path>` in src/App.tsx and src/routes/groups/*Routes.tsx. "Guard" = wrapper component found inside the route element; no guard means the route is public (or guarded elsewhere — verify).') +
    `Total: **${rows.length}** routes. Guard components: ${GUARDS.map((g) => `\`${g}\``).join(', ')}.\n\n`
  if (unguarded.length)
    md += `## Review: dashboard/staff/tech paths with no guard detected (${unguarded.length})\n\n${unguarded.map((r) => `- \`${r.path}\` (${r.file})`).join('\n')}\n\n`
  md += '| Path | Area | Page component | Guard | Defined in |\n|---|---|---|---|---|\n'
  for (const r of rows) md += `| \`${esc(r.path)}\` | ${area(r.path)} | ${r.page === '—' ? '—' : `\`${r.page}\``} | ${code(r.guards)} | ${r.file} |\n`
  files.set('ROUTES.md', md)
}

// ---------------------------------------------------------------- webhooks
{
  const cfg = existsSync('supabase/config.toml') ? read('supabase/config.toml') : ''
  const noJwt = new Set([...cfg.matchAll(/\[functions\.([a-z0-9-]+)\]\s*\n\s*verify_jwt\s*=\s*false/gi)].map((m) => m[1]))
  const names = readdirSync('supabase/functions').filter((n) => !n.startsWith('_') && existsSync(`supabase/functions/${n}/index.ts`))
  const rows = []
  for (const n of names) {
    const src = read(`supabase/functions/${n}/index.ts`)
    const nameHit = /webhook|callback|ingest|inbound/.test(n)
    const sigHit = /createHmac|hmac|timingSafeEqual|constructEvent|verifySignature|stripe-signature|x-hub-signature|x-signature|svix|x-twilio-signature/i.test(src)
    if (!nameHit && !sigHit) continue
    if (!nameHit && !/webhook/i.test(src)) continue
    const sig = [
      /stripe-signature|constructEvent/i.test(src) && 'Stripe signature',
      /x-twilio-signature/i.test(src) && 'Twilio signature',
      /svix/i.test(src) && 'Svix',
      /x-hub-signature/i.test(src) && 'X-Hub-Signature',
      /createHmac|hmac/i.test(src) && 'HMAC',
      /timingSafeEqual/i.test(src) && 'constant-time compare',
    ].filter(Boolean)
    const replay = [
      /idempoten/i.test(src) && 'idempotency',
      /replay/i.test(src) && 'replay',
      /(webhook|event)s?_(events|log|received|dedup)|on conflict|upsert\(/i.test(src) && 'dedupe/upsert',
      /tolerance|timestamp/i.test(src) && 'timestamp',
    ].filter(Boolean)
    const secrets = [...new Set([...src.matchAll(/Deno\.env\.get\(['"]([A-Z0-9_]+)['"]\)/g)].map((m) => m[1]))].filter((s) => /SECRET|SIGN|TOKEN|KEY/.test(s))
    rows.push({ n, jwt: noJwt.has(n) || new RegExp(`functions deploy ${n} --no-verify-jwt`).test(src) ? 'verify_jwt=false' : 'gateway JWT / unknown', sig, replay, secrets })
  }
  let md =
    header('Webhook & callback catalog', 'Source: supabase/functions/*/index.ts (name contains webhook/callback/ingest/inbound, or signature code + "webhook" present). Columns are regex detections — read the function for the real contract. Provider-side retry policy is NOT derivable from code: see the provider docs.') +
    `Total: **${rows.length}** functions. Rows with an empty signature column deserve a manual review.\n\n| Function | Gateway | Signature evidence | Replay / idempotency evidence | Secrets read |\n|---|---|---|---|---|\n`
  for (const r of rows) md += `| \`${r.n}\` | ${r.jwt} | ${r.sig.length ? r.sig.join(', ') : '**none detected**'} | ${r.replay.length ? r.replay.join(', ') : 'none detected'} | ${code(r.secrets)} |\n`
  files.set('WEBHOOKS.md', md)
}

// ---------------------------------------------------------------- cron
{
  const rows = []
  for (const f of readdirSync('supabase/migrations').filter((x) => x.endsWith('.sql')).sort()) {
    const lines = read(join('supabase/migrations', f)).split('\n')
    lines.forEach((line, i) => {
      const m = line.match(/cron\.schedule\(\s*'([^']+)'\s*,\s*'([^']+)'\s*,?\s*(.*)$/)
      if (m) rows.push({ name: m[1], expr: m[2], file: f, line: i + 1, active: !/^\s*--/.test(line), cmd: m[3].replace(/\$cron\$|\$\$/g, '').slice(0, 70) })
      const u = line.match(/cron\.unschedule\(\s*'([^']+)'/)
      if (u && !/^\s*--/.test(line)) rows.push({ name: u[1], expr: '(unschedule)', file: f, line: i + 1, active: false, cmd: 'removed' })
    })
  }
  const act = rows.filter((r) => r.active && r.expr !== '(unschedule)')
  let md =
    header('Scheduled jobs (pg_cron) catalog', 'Source: `cron.schedule(` / `cron.unschedule(` in supabase/migrations. "Commented" rows are documentation-only examples that are NOT scheduled by the migration. The live schedule in your database may differ — verify with `select * from cron.job;`.') +
    `Active in migrations: **${act.length}** · commented examples: **${rows.filter((r) => !r.active && r.expr !== '(unschedule)').length}** · unschedules: **${rows.filter((r) => r.expr === '(unschedule)').length}**\n\n| Job | Schedule | Status | Command (start) | Migration:line |\n|---|---|---|---|---|\n`
  for (const r of rows) md += `| \`${esc(r.name)}\` | \`${esc(r.expr)}\` | ${r.expr === '(unschedule)' ? 'unscheduled' : r.active ? 'active' : 'commented'} | ${r.cmd ? `\`${esc(r.cmd)}\`` : '—'} | ${r.file}:${r.line} |\n`
  const cronFns = readdirSync('supabase/functions')
    .filter((n) => !n.startsWith('_') && existsSync(`supabase/functions/${n}/index.ts`) && /CRON_SECRET/.test(read(`supabase/functions/${n}/index.ts`)))
  md += `\n## Functions that check a cron secret (${cronFns.length})\n\nThese are intended to be invoked by a scheduler; owner and failure handling must be recorded per function.\n\n${cronFns.map((n) => `\`${n}\``).join(' · ')}\n`
  files.set('CRON_CATALOG.md', md)
}

// ---------------------------------------------------------------- scripts
{
  const pkg = JSON.parse(read('package.json'))
  const rows = Object.entries(pkg.scripts ?? {}).map(([k, v]) => {
    const f = v.match(/node\s+(scripts\/[^\s]+\.mjs)/)?.[1]
    let desc = ''
    if (f && existsSync(f)) {
      const lines = read(f).split('\n').slice(0, 14).filter((l) => /^\s*\/\/(?!\s*(?:scripts\/|Usage|usage))/.test(l) && !/^#!/.test(l))
      desc = lines.map((l) => l.replace(/^\s*\/\/\s?/, '').trim()).filter(Boolean)[0] ?? ''
    }
    return { k, v, desc }
  })
  const missing = rows.filter((r) => !r.desc)
  let md =
    header('npm scripts', 'Source: package.json "scripts". Description = first comment line in the referenced scripts/*.mjs file, when there is one.') +
    `Total: **${rows.length}** · without a description: **${missing.length}** (add a header comment to the script file, or document it in CONTRIBUTING.md).\n\n| Script | Command | Description |\n|---|---|---|\n`
  for (const r of rows) md += `| \`npm run ${esc(r.k)}\` | \`${esc(r.v).slice(0, 110)}\` | ${r.desc ? esc(r.desc) : '_undocumented_'} |\n`
  files.set('SCRIPTS.md', md)
}

// ---------------------------------------------------------------- integrations
{
  const PROVIDERS = {
    Stripe: /stripe/i, Twilio: /twilio/i, Vapi: /vapi/i, Telnyx: /telnyx/i, Resend: /resend/i, SendGrid: /sendgrid/i,
    OpenAI: /openai/i, Anthropic: /anthropic/i, Gemini: /gemini/i, ElevenLabs: /elevenlabs/i, Deepgram: /deepgram/i,
    'Google (Calendar/Business/Ads)': /google/i, Microsoft: /microsoft|graph\.microsoft/i, QuickBooks: /quickbooks/i, Xero: /\bxero\b/i,
    NetSuite: /netsuite/i, Gusto: /gusto/i, Checkr: /checkr/i, Plaid: /plaid/i, Zapier: /zapier/i, Housecall: /housecall/i,
    Slack: /slack/i, 'Microsoft Teams': /teams/i, Cloudflare: /cloudflare/i, Daily: /daily\.co|DAILY_API/i, APNs: /apns/i, FCM: /fcm/i,
  }
  const srcFiles = [...walk('supabase/functions'), ...walk('src/lib')].filter((f) => /\.(ts|tsx)$/.test(f) && !/\.test\./.test(f))
  const docs = ['README.md', 'ARCHITECTURE.md', 'RUNBOOK.md', 'ENVIRONMENT.md', 'VOICE_RUNBOOK.md', 'XERO_SYNC.md', ...walk('docs').filter((f) => f.endsWith('.md') && !f.includes('/generated/'))].filter(existsSync)
  const docText = new Map(docs.map((d) => [d, read(d)]))
  const srcText = srcFiles.map((f) => [f, read(f)])
  let md = header('Third-party integrations', 'Source: keyword scan of supabase/functions and src/lib (non-test). "Setup docs" = markdown files that mention the provider; open them to confirm they cover keys, webhooks, scopes and sandbox vs production.') +
    '| Provider | Code files | Setup/ops docs mentioning it |\n|---|---:|---|\n'
  for (const [p, re] of Object.entries(PROVIDERS)) {
    const n = srcText.filter(([, t]) => re.test(t)).length
    if (!n) continue
    const d = docs.filter((x) => re.test(docText.get(x)) && !x.endsWith('compliance/SOC2_READINESS.md'))
    md += `| ${p} | ${n} | ${d.length ? d.slice(0, 6).map((x) => `\`${x}\``).join(', ') + (d.length > 6 ? ` (+${d.length - 6})` : '') : '**none**'} |\n`
  }
  files.set('INTEGRATIONS.md', md)
}

// ---------------------------------------------------------------- write / check
mkdirSync(OUT, { recursive: true })
let stale = 0
for (const [name, content] of files) {
  const p = join(OUT, name)
  if (CHECK) {
    if (!existsSync(p) || read(p) !== content) { console.error(`stale: ${p}`); stale++ }
  } else {
    writeFileSync(p, content)
    console.log(`wrote ${p}`)
  }
}
if (CHECK && stale) { console.error('Run: npm run docs:catalogs'); process.exit(1) }
