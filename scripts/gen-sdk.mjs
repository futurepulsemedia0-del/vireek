#!/usr/bin/env node
/**
 * Generates the typed TypeScript SDK (packages/sdk/src/index.ts) from supabase/functions/api-v1/contract.ts.
 *   node scripts/gen-sdk.mjs generate   write the file
 *   node scripts/gen-sdk.mjs check      exit 1 if the committed file differs (CI)
 * Needs Node >= 22.18 (native TypeScript).
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'packages/sdk/src/index.ts');
const c = await import(pathToFileURL(resolve(ROOT, 'supabase/functions/api-v1/contract.ts')).href);

const tsType = (f) => {
  const base =
    f.type === 'array'
      ? 'string[]'
      : f.type === 'integer' || f.type === 'number'
        ? 'number'
        : f.type;
  return f.nullable ? `${base} | null` : base;
};

function render() {
  const ifaces = c.RESOURCES.map((r) => {
    const lines = r.fields.map((f) => `  /** ${f.description} */\n  ${f.name}: ${tsType(f)};`);
    return `/** ${r.description} */\nexport interface ${r.schema} {\n${lines.join('\n')}\n  /** false on records returned to test keys. */\n  livemode?: boolean;\n  [extra: string]: unknown;\n}`;
  }).join('\n\n');
  const props = c.RESOURCES.map((r) => `  readonly ${r.name}: Resource<${r.schema}>;`).join('\n');
  const inits = c.RESOURCES.map(
    (r) => `    this.${r.name} = new Resource<${r.schema}>(this.request, '${r.name}');`,
  ).join('\n');
  return `// GENERATED by scripts/gen-sdk.mjs from supabase/functions/api-v1/contract.ts — DO NOT EDIT.
// API contract version ${c.API_VERSION}. Regenerate with: node scripts/gen-sdk.mjs generate

export const API_VERSION = '${c.API_VERSION}';

${ifaces}

export interface Page<T> {
  data: T[];
  has_more: boolean;
  next_before: string | null;
}

export interface ListParams {
  /** 1–${c.MAX_LIMIT}, default ${c.DEFAULT_LIMIT}. */
  limit?: number;
  /** Pass the previous page's next_before. */
  before?: string;
}

export type ErrorCode = ${c.ERROR_CATALOG.map((e) => `'${e.code}'`).join(' | ')};

/** Thrown for every non-2xx response. Branch on \`code\`, never on \`message\`. */
export class VireekError extends Error {
  readonly status: number;
  readonly code: ErrorCode | 'unknown';
  readonly docUrl: string | null;
  readonly requestId: string | null;
  readonly retryAfterSeconds: number | null;
  constructor(init: { status: number; message: string; code?: string; docUrl?: string; requestId?: string; retryAfterSeconds?: number | null }) {
    super(init.message);
    this.name = 'VireekError';
    this.status = init.status;
    this.code = (init.code as ErrorCode | undefined) ?? 'unknown';
    this.docUrl = init.docUrl ?? null;
    this.requestId = init.requestId ?? null;
    this.retryAfterSeconds = init.retryAfterSeconds ?? null;
  }
}

export interface ClientOptions {
  /** vrk_test_… for synthetic data, vrk_live_… for real data. Never hard-code it; read it from the environment. */
  apiKey: string;
  /** e.g. https://<project-ref>.supabase.co/functions/v1/api-v1 */
  baseUrl: string;
  /** Retries for 429 (honouring Retry-After, max 30 s) and 5xx on GET. Default 2. */
  maxRetries?: number;
  fetch?: typeof fetch;
}

type Requester = (path: string, query?: Record<string, string | number | undefined>) => Promise<unknown>;

class Resource<T> {
  constructor(
    private readonly request: Requester,
    private readonly name: string,
  ) {}

  list(params: ListParams = {}): Promise<Page<T>> {
    return this.request(\`/\${this.name}\`, { limit: params.limit, before: params.before }) as Promise<Page<T>>;
  }

  async get(id: string): Promise<T> {
    const body = (await this.request(\`/\${this.name}/\${encodeURIComponent(id)}\`)) as { data: T };
    return body.data;
  }

  /** Iterates every record, newest first, following next_before until the last page. */
  async *iterate(params: Omit<ListParams, 'before'> = {}): AsyncGenerator<T, void, undefined> {
    let before: string | undefined;
    for (;;) {
      const page = await this.list({ ...params, before });
      yield* page.data;
      const size = params.limit ?? ${c.DEFAULT_LIMIT};
      if (!page.next_before || page.data.length < Math.min(size, ${c.MAX_LIMIT})) return;
      before = page.next_before;
    }
  }
}

export class Vireek {
${props}
  private readonly opts: Required<Omit<ClientOptions, 'fetch'>> & { fetch: typeof fetch };

  constructor(options: ClientOptions) {
    if (!options.apiKey) throw new Error('Vireek: apiKey is required');
    if (!options.baseUrl) throw new Error('Vireek: baseUrl is required');
    this.opts = { maxRetries: 2, ...options, baseUrl: options.baseUrl.replace(/\\/+$/, ''), fetch: options.fetch ?? globalThis.fetch.bind(globalThis) };
${inits}
  }

  private request: Requester = async (path, query = {}) => {
    const url = new URL(this.opts.baseUrl + path);
    for (const [k, v] of Object.entries(query)) if (v !== undefined) url.searchParams.set(k, String(v));
    for (let attempt = 0; ; attempt++) {
      const res = await this.opts.fetch(url, { headers: { Authorization: \`Bearer \${this.opts.apiKey}\`, Accept: 'application/json' } });
      if (res.ok) return res.json();
      const retryable = res.status === 429 || res.status >= 500;
      const header = Number(res.headers.get('Retry-After'));
      if (retryable && attempt < this.opts.maxRetries) {
        const wait = res.status === 429 && header > 0 ? Math.min(header, 30) * 1000 : 250 * 2 ** attempt;
        await new Promise((r) => setTimeout(r, wait));
        continue;
      }
      let body: { error?: string; code?: string; doc_url?: string; request_id?: string } = {};
      try {
        body = await res.json();
      } catch {
        /* non-JSON error body */
      }
      throw new VireekError({
        status: res.status,
        message: body.error ?? \`HTTP \${res.status}\`,
        code: body.code,
        docUrl: body.doc_url,
        requestId: body.request_id ?? res.headers.get('X-Request-Id') ?? undefined,
        retryAfterSeconds: header > 0 ? header : null,
      });
    }
  };
}
`;
}

const mode = process.argv[2];
if (mode !== 'generate' && mode !== 'check') {
  console.error('Usage: node scripts/gen-sdk.mjs <generate|check>');
  process.exit(2);
}
const out = render();
if (mode === 'generate') {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, out);
  console.log('✔ Wrote packages/sdk/src/index.ts');
} else if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== out) {
  console.error(
    '✖ packages/sdk/src/index.ts is out of date. Run: node scripts/gen-sdk.mjs generate',
  );
  process.exit(1);
} else console.log('✔ SDK in sync with the contract');
