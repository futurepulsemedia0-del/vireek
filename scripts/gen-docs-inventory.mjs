#!/usr/bin/env node
// scripts/gen-docs-inventory.mjs
//
// Regenerates the machine-derived inventories linked from ARCHITECTURE.md and
// ENVIRONMENT.md, straight from the CURRENT code (no hand-maintained lists):
//
//   docs/generated/TABLES.md          every CREATE TABLE in supabase/migrations
//   docs/generated/EDGE_FUNCTIONS.md  every supabase/functions/<name>/index.ts
//   docs/generated/ENV_USAGE.md       every env var read by src/, supabase/functions/, scripts/, e2e/
//
// Usage:  npm run docs:inventory        (plain Node, no dependencies)
//         npm run docs:inventory -- --check   exit 1 if committed files are stale

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs'
import { join, basename } from 'node:path'

const CHECK = process.argv.includes('--check')
const OUT = 'docs/generated'
const walk = (d) =>
  readdirSync(d).flatMap((n) => {
    const p = join(d, n)
    return statSync(p).isDirectory() ? (n === 'node_modules' ? [] : walk(p)) : [p]
  })
const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1').replace(/--[^\n]*/g, ' ')
const md = (rows) => rows.join('\n') + '\n'
const header = (title, how) =>
  `# ${title}\n\n> Generated by \`npm run docs:inventory\` — do not edit by hand.\n> ${how}\n\n`

// ---- tables ----------------------------------------------------------------
const tables = new Map()
for (const f of readdirSync('supabase/migrations').filter((x) => x.endsWith('.sql')).sort()) {
  const sql = stripComments(readFileSync(join('supabase/migrations', f), 'utf8'))
  for (const m of sql.matchAll(/create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?([a-z0-9_]+)"?/gi)) {
    const t = m[1].toLowerCase()
    if (!tables.has(t)) tables.set(t, f)
  }
}
const tablesMd =
  header('Database tables', 'Source: `CREATE TABLE` statements in supabase/migrations (first migration that creates each table).') +
  `Total: **${tables.size}** tables.\n\n| Table | First created in |\n|---|---|\n` +
  md([...tables].sort(([a], [b]) => a.localeCompare(b)).map(([t, f]) => `| \`${t}\` | \`${f}\` |`))

// ---- functions -------------------------------------------------------------
const PLATFORM = new Set(['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'SUPABASE_SERVICE_ROLE_KEY'])
const envRe = /Deno\.env\.get\(\s*['"]([A-Z0-9_]+)['"]/g
const fnRows = []
for (const n of readdirSync('supabase/functions').sort()) {
  const idx = join('supabase/functions', n, 'index.ts')
  if (n === '_shared' || !existsSync(idx)) continue
  const raw = readFileSync(idx, 'utf8')
  const code = stripComments(raw)
  const envs = [...new Set([...code.matchAll(envRe)].map((m) => m[1]))].filter((e) => !PLATFORM.has(e))
  const secretGates = envs.filter((e) => /(CRON|WEBHOOK|SERVER|DISPATCH)_SECRET$|^CRON_SECRET$|VERIFY_TOKEN$/.test(e))
  const gate = []
  if (/no-verify-jwt/.test(raw)) gate.push('deployed `--no-verify-jwt`')
  if (secretGates.length) gate.push('secret: ' + secretGates.map((e) => `\`${e}\``).join(', '))
  if (/getUser\(|Bearer/.test(code)) gate.push('Bearer/JWT handling')
  const tabs = new Map()
  for (const m of code.matchAll(/\.from\(\s*['"]([a-z0-9_]+)['"]/g)) tabs.set(m[1], (tabs.get(m[1]) ?? 0) + 1)
  const top = [...tabs].sort((a, b) => b[1] - a[1]).slice(0, 4).map(([t]) => `\`${t}\``)
  fnRows.push(`| \`${n}\` | ${gate.join('; ') || '—'} | ${envs.map((e) => `\`${e}\``).join(', ') || '—'} | ${top.join(', ') || '—'} |`)
}
const fnMd =
  header('Edge functions', 'Source: supabase/functions/*/index.ts (static scan; "Gate" is detected from the source, read the file header for the full contract).') +
  `Total: **${fnRows.length}** functions.\n\n| Function | Gate (detected) | Secrets read | Main tables (\`.from()\`) |\n|---|---|---|---|\n` +
  md(fnRows)

// ---- env usage --------------------------------------------------------------
const uses = new Map()
const add = (k, where) => uses.set(k, (uses.get(k) ?? new Set()).add(where))
const scan = (dir, patterns) => {
  if (!existsSync(dir)) return
  for (const f of walk(dir).filter((x) => /\.(m?[jt]sx?)$/.test(x) && !/\.test\./.test(x))) {
    const code = readFileSync(f, 'utf8')
    for (const re of patterns) for (const m of code.matchAll(re)) add(m[1], f.replaceAll('\\', '/'))
  }
}
scan('src', [/import\.meta\.env\.([A-Z0-9_]+)/g])
scan('supabase/functions', [envRe])
scan('scripts', [/process\.env\.([A-Z0-9_]+)/g])
scan('e2e', [/process\.env\.([A-Z0-9_]+)/g])
for (const f of ['vite.config.ts', 'playwright.config.ts']) {
  if (existsSync(f)) for (const m of readFileSync(f, 'utf8').matchAll(/process\.env\.([A-Z0-9_]+)/g)) add(m[1], f)
}
const envMd =
  header('Environment variable usage', 'Source: static scan of src/, supabase/functions/, scripts/, e2e/ and the Vite/Playwright configs. Dynamic names (e.g. STRIPE_PRICE_<PLAN>) are not detected.') +
  `Total: **${uses.size}** variables.\n\n| Variable | Read in |\n|---|---|\n` +
  md([...uses].sort(([a], [b]) => a.localeCompare(b)).map(([k, s]) => {
    const files = [...s].sort()
    const shown = files.slice(0, 4).map((x) => `\`${x}\``).join(', ')
    return `| \`${k}\` | ${shown}${files.length > 4 ? ` (+${files.length - 4} more)` : ''} |`
  }))

// ---- write / check ----------------------------------------------------------
const outputs = { 'TABLES.md': tablesMd, 'EDGE_FUNCTIONS.md': fnMd, 'ENV_USAGE.md': envMd }
mkdirSync(OUT, { recursive: true })
let stale = false
for (const [name, content] of Object.entries(outputs)) {
  const p = join(OUT, basename(name))
  if (CHECK) {
    if (!existsSync(p) || readFileSync(p, 'utf8') !== content) { console.error(`stale: ${p}`); stale = true }
  } else {
    writeFileSync(p, content)
    console.log(`wrote ${p}`)
  }
}
process.exit(CHECK && stale ? 1 : 0)
