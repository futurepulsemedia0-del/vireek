// Pure core of the payments / e-invoicing matrix (no I/O, no clock).
// Data: config/global/payments-einvoicing.json   Doc: docs/global/payments-einvoicing.md (generated block)
// CLI: scripts/global/payments-einvoicing.mjs     Tests: scripts/lib/paymentsEinvoicing.test.mjs
// DB gate: supabase/migrations/20290311000000_billing_region_gate.sql (a pack cannot be enabled until cleared).

import { createHash } from 'node:crypto'

export const MANDATE_VALUES = ['mandatory', 'phased', 'voluntary', 'none', 'unknown']
export const SUPPORT_VALUES = ['unassessed', 'not_required', 'none', 'partial', 'implemented']
export const DEFAULT_REGION = 'US' // mirrors DEFAULT_REGION_COUNTRY in src/lib/regionConfig/gate.ts: never gated
export const DOC_BEGIN = '<!-- payments-einvoicing:begin (generated by npm run payments-einvoicing:write; do not edit by hand) -->'
export const DOC_END = '<!-- payments-einvoicing:end -->'
const DAY_MS = 86_400_000
const ISO_DAY = /^\d{4}-\d{2}-\d{2}$/

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v)
const str = (v) => (typeof v === 'string' ? v.trim() : '')

export function isIsoDay(v) {
  if (typeof v !== 'string' || !ISO_DAY.test(v)) return false
  const d = new Date(`${v}T00:00:00Z`)
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === v
}
const ageDays = (iso, today) => Math.round((Date.parse(`${today}T00:00:00Z`) - Date.parse(`${iso}T00:00:00Z`)) / DAY_MS)
const isHttps = (s) => { try { return new URL(s).protocol === 'https:' } catch { return false } }

/** What is still missing or invalid on one row. Empty array = the row is complete. */
export function rowMissing(row, { today, maxAgeDays = 365 }) {
  const m = []
  if (!isObj(row)) return ['row is not an object']
  if (!Array.isArray(row.localMethods) || row.localMethods.length === 0 || row.localMethods.some((x) => !str(x))) m.push('localMethods')
  if (str(row.taxInvoiceRequirements).length < 20) m.push('taxInvoiceRequirements')
  const e = isObj(row.eInvoicing) ? row.eInvoicing : {}
  if (!MANDATE_VALUES.includes(e.b2b) || e.b2b === 'unknown') m.push('eInvoicing.b2b')
  if (!MANDATE_VALUES.includes(e.b2g) || e.b2g === 'unknown') m.push('eInvoicing.b2g')
  if (!SUPPORT_VALUES.includes(e.vireekSupport) || e.vireekSupport === 'unassessed') m.push('eInvoicing.vireekSupport')
  const mandated = ['mandatory', 'phased'].includes(e.b2b) || ['mandatory', 'phased'].includes(e.b2g)
  if (mandated) {
    if (!str(e.system)) m.push('eInvoicing.system')
    if (e.vireekSupport !== 'implemented' && !str(e.workaround)) m.push('eInvoicing.workaround (mandate without implemented support)')
  }
  const v = isObj(row.verification) ? row.verification : {}
  if (v.status !== 'verified') m.push('verification.status')
  if (!isHttps(str(v.source))) m.push('verification.source (https URL)')
  if (!str(v.reviewer)) m.push('verification.reviewer')
  if (!str(v.counselReviewer)) m.push('verification.counselReviewer')
  for (const k of ['verifiedOn', 'counselReviewedOn']) {
    if (!isIsoDay(v[k])) m.push(`verification.${k}`)
    else if (v[k] > today) m.push(`verification.${k} (in the future)`)
    else if (ageDays(v[k], today) > maxAgeDays) m.push(`verification.${k} (older than ${maxAgeDays} days)`)
  }
  return m
}

/** Structural validation of the whole file against the real regional packs. */
export function validateMatrix(cfg, { packs }) {
  const errors = []
  if (!isObj(cfg)) return ['config must be an object']
  if (cfg.schemaVersion !== 1) errors.push('schemaVersion must be 1')
  if (!Number.isInteger(cfg.verificationMaxAgeDays) || cfg.verificationMaxAgeDays < 30 || cfg.verificationMaxAgeDays > 730) errors.push('verificationMaxAgeDays must be an integer between 30 and 730')
  if (!Array.isArray(cfg.rows)) return [...errors, 'rows must be an array']
  const seen = new Set()
  const owner = new Map()
  for (const [code, p] of Object.entries(packs)) for (const c of p.countries) owner.set(c, code)
  for (const r of cfg.rows) {
    const id = isObj(r) ? r.country : null
    if (typeof id !== 'string' || !/^[A-Z]{2}$/.test(id)) { errors.push('every row needs an ISO country code'); continue }
    if (seen.has(id)) errors.push(`${id}: duplicate row`)
    seen.add(id)
    if (!owner.has(id)) { errors.push(`${id}: not a country of any regional pack`); continue }
    if (r.pack !== owner.get(id)) errors.push(`${id}: pack must be ${owner.get(id)}`)
    const e = r.eInvoicing
    if (!isObj(e)) { errors.push(`${id}: eInvoicing missing`); continue }
    if (!MANDATE_VALUES.includes(e.b2b)) errors.push(`${id}: eInvoicing.b2b must be one of ${MANDATE_VALUES.join(', ')}`)
    if (!MANDATE_VALUES.includes(e.b2g)) errors.push(`${id}: eInvoicing.b2g must be one of ${MANDATE_VALUES.join(', ')}`)
    if (!SUPPORT_VALUES.includes(e.vireekSupport)) errors.push(`${id}: eInvoicing.vireekSupport must be one of ${SUPPORT_VALUES.join(', ')}`)
    if (!isObj(r.verification) || !['unverified', 'verified'].includes(r.verification.status)) errors.push(`${id}: verification.status must be unverified or verified`)
    if (!Array.isArray(r.localMethods)) errors.push(`${id}: localMethods must be an array`)
  }
  for (const c of owner.keys()) if (!seen.has(c)) errors.push(`${c}: missing row (every supported country needs one)`)
  return errors
}

const canonical = (v) => Array.isArray(v) ? v.map(canonical)
  : isObj(v) ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, canonical(v[k])])) : v

/** Stable SHA-256 over the pack's rows (sorted by country, keys sorted). Staff paste it when clearing a pack. */
export function packHash(cfg, packCode) {
  const rows = cfg.rows.filter((r) => r.pack === packCode).sort((a, b) => a.country.localeCompare(b.country))
  return createHash('sha256').update(JSON.stringify(canonical(rows))).digest('hex')
}

export function evaluatePacks(cfg, { packs, today }) {
  return Object.entries(packs).map(([code, p]) => {
    const rows = p.countries.map((country) => {
      const row = cfg.rows.find((r) => r.country === country)
      const missing = row ? rowMissing(row, { today, maxAgeDays: cfg.verificationMaxAgeDays }) : ['row missing']
      return { country, complete: missing.length === 0, missing }
    })
    const gated = code !== DEFAULT_REGION
    const complete = rows.every((r) => r.complete)
    return {
      code, name: p.name, gated, rows, complete,
      // US is the default region and is never gated; others may be cleared in the database only when complete.
      mayBeCleared: !gated || complete,
      hash: packHash(cfg, code),
    }
  })
}

/* ------------------------------ rendering ---------------------------- */

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')

export function renderTables(cfg, { packs, knownMethods }) {
  const L = []
  for (const [code, p] of Object.entries(packs)) {
    L.push(`### ${code} - ${p.name}`, '')
    L.push(`${code === DEFAULT_REGION ? 'Default region: never blocked by the billing gate, but the row is still tracked. ' : 'Billing for this pack stays blocked until every row below is complete and the pack is cleared in the database. '}All cells are **[VERIFY]** until the Verification column says verified.`, '')
    L.push('| Country | Local methods | Tax invoice requirements [VERIFY] | E-invoicing B2B / B2G / system [VERIFY] | Vireek support | Verification |')
    L.push('| --- | --- | --- | --- | --- | --- |')
    for (const c of p.countries) {
      const r = cfg.rows.find((x) => x.country === c)
      if (!r) { L.push(`| ${c} | missing | | | | |`); continue }
      const methods = r.localMethods.map((m) => (knownMethods.includes(m) ? `\`${m}\`` : `${m} (not in code)`)).join(', ')
      const e = r.eInvoicing
      const sys = `${e.b2b} / ${e.b2g}${e.system ? ` / ${e.system}` : ''}${e.note ? `. ${e.note}` : ''}`
      const support = e.vireekSupport + (e.workaround ? ` (workaround: ${e.workaround})` : '')
      const v = r.verification
      const ver = v.status === 'verified' ? `verified ${v.verifiedOn ?? '?'}` : 'unverified [VERIFY]'
      L.push(`| ${c} | ${cell(methods)} | ${cell(r.taxInvoiceRequirements)} | ${cell(sys)} | ${cell(support)} | ${ver} |`)
    }
    L.push('')
  }
  return L.join('\n')
}

export function injectBlock(doc, block) {
  const a = doc.indexOf(DOC_BEGIN); const b = doc.indexOf(DOC_END)
  if (a === -1 || b === -1 || b < a) throw new Error('doc is missing the generated-block markers')
  return `${doc.slice(0, a)}${DOC_BEGIN}\n\n${block}\n${doc.slice(b)}`
}
export const extractBlock = (doc) => {
  const a = doc.indexOf(DOC_BEGIN); const b = doc.indexOf(DOC_END)
  return a === -1 || b === -1 ? null : doc.slice(a, b + DOC_END.length)
}

export function renderStatus(results) {
  const L = []
  for (const p of results) {
    L.push(`${p.code.padEnd(3)} ${p.complete ? 'COMPLETE  ' : 'INCOMPLETE'} ${p.gated ? 'gated  ' : 'default'} ${p.rows.filter((r) => r.complete).length}/${p.rows.length} rows  sha256:${p.hash.slice(0, 12)}...  ${p.name}`)
  }
  return L.join('\n')
}
