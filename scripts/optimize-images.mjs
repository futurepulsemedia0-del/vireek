#!/usr/bin/env node
// Build-time image pipeline. Needs: npm i -D sharp
//   node scripts/optimize-images.mjs          -> AVIF + WebP at several widths into public/img/, writes src/lib/images.generated.ts
//   node scripts/optimize-images.mjs --og     -> also recompresses public/og-image.png (1200x630, palette PNG)
// Originals stay in place (press kit downloads, <img> fallback). Re-run when a source image changes.
import { readdirSync, mkdirSync, writeFileSync, statSync } from 'node:fs'
import { join, parse } from 'node:path'
import sharp from 'sharp'

const SRC = 'public'
const OUT = 'public/img'
const WIDTHS = [480, 800, 1200, 1600]
const SKIP = /^(og-image|apple|icon|favicon|android|logo|manifest)/i
mkdirSync(OUT, { recursive: true })

const meta = {}
for (const file of readdirSync(SRC)) {
  const { name, ext } = parse(file)
  if (!/^\.(png|jpe?g)$/i.test(ext) || SKIP.test(name)) continue
  const input = join(SRC, file)
  if (!statSync(input).isFile()) continue
  const { width = 0, height = 0 } = await sharp(input).metadata()
  if (!width || !height) continue
  const widths = [...new Set(WIDTHS.filter((w) => w < width).concat(width))].sort((a, b) => a - b)
  for (const w of widths) {
    const img = sharp(input).resize({ width: w, withoutEnlargement: true })
    await img.clone().avif({ quality: 50, effort: 6 }).toFile(join(OUT, `${name}-${w}.avif`))
    await img.clone().webp({ quality: 74, effort: 5 }).toFile(join(OUT, `${name}-${w}.webp`))
  }
  meta[name] = { width, height, widths }
  console.log(`${file}: ${widths.join(', ')}`)
}

if (process.argv.includes('--og')) {
  const og = join(SRC, 'og-image.png')
  const buf = await sharp(og).resize(1200, 630, { fit: 'cover' }).png({ palette: true, quality: 80, compressionLevel: 9 }).toBuffer()
  writeFileSync(og, buf)
  console.log(`og-image.png -> ${(buf.length / 1024).toFixed(0)} KB`)
}

const body = Object.entries(meta)
  .map(([k, v]) => `  '${k}': { width: ${v.width}, height: ${v.height}, widths: [${v.widths.join(', ')}] },`)
  .join('\n')
writeFileSync(
  'src/lib/images.generated.ts',
  `// GENERATED by scripts/optimize-images.mjs — do not edit.\nexport interface ImageMeta {\n  width: number;\n  height: number;\n  widths: number[];\n}\nexport const IMAGES: Record<string, ImageMeta> = {\n${body}\n};\n`,
)
