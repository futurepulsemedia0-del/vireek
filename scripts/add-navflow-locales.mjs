const nest = (values) => {
  const out = {};
  KEYS.forEach((key, i) => {
    const parts = key.split('.');
    let d = out;
    for (const p of parts.slice(0, -1)) d = d[p] ??= {};
    d[parts[parts.length - 1]] = values[i];
  });
  return out;
};

let changed = 0;
for (const [code, values] of Object.entries(STRINGS)) {
  if (values.length !== KEYS.length) throw new Error(`${code}: ${values.length} strings for ${KEYS.length} keys`);
  const file = resolve(ROOT, 'src/locales', code, 'common.json');
  const json = JSON.parse(readFileSync(file, 'utf8'));
  const next = nest(values);
  if (JSON.stringify(json.navflow ?? null) !== JSON.stringify(next)) {
    json.navflow = next;
    writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
    changed++;
  }
}
console.log(`navflow locale strings: ${changed} file(s) updated, ${Object.keys(STRINGS).length - changed} already current.`);
