#!/usr/bin/env node
// Regenerates the /locations block in public/sitemap.xml (idempotent).
// Run: npm run sitemap:locations   (re-run whenever cities or trades change)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

const tradeSlugs = [...read('src/lib/industries.ts').matchAll(/^\s{4}slug:\s*'([^']+)'/gm)].map((m) => m[1]);
const citySlugs = [...read('src/lib/locations.ts').matchAll(/^\s{4}slug:\s*'([^']+)'/gm)].map((m) => m[1]);
if (!tradeSlugs.length || !citySlugs.length) {
  console.error('Could not parse trade/city slugs — aborting without changes.');
  process.exit(1);
}

const lastmod = new Date().toISOString().slice(0, 10);
const entry = (path, priority) =>
  `  <url>\n    <loc>https://vireek.com${path}</loc>\n    <lastmod>${lastmod}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>${priority}</priority>\n  </url>`;

const entries = [
  entry('/locations', '0.7'),
  ...citySlugs.flatMap((c) => [
    entry(`/locations/${c}`, '0.6'),
    ...tradeSlugs.map((t) => entry(`/locations/${c}/${t}`, '0.5')),
  ]),
];

const START = '  <!-- locations:start (generated by scripts/generate-locations-sitemap.mjs) -->';
const END = '  <!-- locations:end -->';
const block = `${START}\n${entries.join('\n')}\n${END}`;

const file = join(ROOT, 'public/sitemap.xml');
let xml = readFileSync(file, 'utf8');
const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
xml = re.test(xml) ? xml.replace(re, block) : xml.replace('</urlset>', `${block}\n</urlset>`);
writeFileSync(file, xml);
console.log(`Wrote ${entries.length} /locations URLs to public/sitemap.xml`);
