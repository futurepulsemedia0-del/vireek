#!/usr/bin/env node
// Copies OFL WOFF2 files (latin + latin-ext) from @fontsource packages into public/fonts, writes
// public/fonts/LICENSES.txt, and generates src/styles/fonts.fallbacks.generated.css
// (metric-compatible, Latin-only fallback faces). Run: npm run fonts:sync
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fromFile } from '@capsizecss/unpack'
import arial from '@capsizecss/metrics/arial'

const NM = 'node_modules'
const OUT = 'public/fonts'
const LATIN =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'

const FILES = [
  ['@fontsource-variable/inter', 'inter-latin-wght-normal.woff2'],
  ['@fontsource-variable/inter', 'inter-latin-ext-wght-normal.woff2'],
  ['@fontsource-variable/source-serif-4', 'source-serif-4-latin-wght-normal.woff2'],
  ['@fontsource-variable/source-serif-4', 'source-serif-4-latin-ext-wght-normal.woff2'],
  ['@fontsource/dancing-script', 'dancing-script-latin-400-normal.woff2'],
  ['@fontsource/caveat', 'caveat-latin-400-normal.woff2'],
  ['@fontsource/great-vibes', 'great-vibes-latin-400-normal.woff2'],
]
const LICENSES = [
  ['@fontsource-variable/inter', 'Inter'],
  ['@fontsource-variable/source-serif-4', 'Source Serif 4'],
  ['@fontsource/dancing-script', 'Dancing Script'],
  ['@fontsource/caveat', 'Caveat'],
  ['@fontsource/great-vibes', 'Great Vibes'],
]
// Metrics are measured on static files at the weight each family is mostly used at.
const METRIC_SOURCES = [
  ['Inter', '@fontsource/inter/files/inter-latin-400-normal.woff2'],
  ['Source Serif 4', '@fontsource/source-serif-4/files/source-serif-4-latin-500-normal.woff2'],
]

const fail = (msg) => {
  console.error(`fonts:sync FAILED — ${msg}`)
  process.exit(1)
}

mkdirSync(OUT, { recursive: true })

for (const [pkg, file] of FILES) {
  const src = join(NM, pkg, 'files', file)
  if (!existsSync(src)) fail(`missing ${src} (package layout changed? run npm i)`)
  copyFileSync(src, join(OUT, file))
}

let licenses =
  'Self-hosted fonts — all licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).\n' +
  'Files are unmodified WOFF2 subsets (latin, latin-ext) distributed by Fontsource (https://fontsource.org).\n\n'
for (const [pkg, name] of LICENSES) {
  const licPath = join(NM, pkg, 'LICENSE')
  if (!existsSync(licPath)) fail(`missing licence file ${licPath}`)
  const { version } = JSON.parse(readFileSync(join(NM, pkg, 'package.json'), 'utf8'))
  licenses += `==== ${name} (${pkg}@${version}) ====\n${readFileSync(licPath, 'utf8').trim()}\n\n`
}
writeFileSync(join(OUT, 'LICENSES.txt'), licenses)

const ratio = (m) => m.xWidthAvg / m.unitsPerEm
const pct = (v) => `${(v * 100).toFixed(2)}%`
let css = '/* GENERATED by scripts/fonts/sync-fonts.mjs (npm run fonts:sync) — do not edit. */\n'
for (const [name, rel] of METRIC_SOURCES) {
  const m = await fromFile(join(NM, rel))
  const values = [m.xWidthAvg, m.unitsPerEm, m.ascent, m.descent, m.lineGap]
  if (!values.every(Number.isFinite)) fail(`could not read metrics for ${name}`)
  const sizeAdjust = ratio(m) / ratio(arial)
  const base = m.unitsPerEm * sizeAdjust
  css +=
    `@font-face{font-family:'${name} Fallback';src:local('Arial'),local('Liberation Sans');` +
    `ascent-override:${pct(m.ascent / base)};descent-override:${pct(Math.abs(m.descent) / base)};` +
    `line-gap-override:${pct(m.lineGap / base)};size-adjust:${pct(sizeAdjust)};unicode-range:${LATIN};}\n`
}
writeFileSync('src/styles/fonts.fallbacks.generated.css', css)
console.log('fonts:sync OK — now run: npm run lint:design && npm test')
