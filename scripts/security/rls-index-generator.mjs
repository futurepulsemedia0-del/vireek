#!/usr/bin/env node
/**
 * Vireek — missing-index generator for RLS policy columns (rule `policy-column-unindexed`).
 * Same catalog export as rls-wrap-generator.mjs. Emits TWO files because CREATE INDEX CONCURRENTLY
 * cannot run inside a transaction block (Supabase applies each migration file in one transaction):
 *   --out-migration  plain `CREATE INDEX IF NOT EXISTS` for SMALL tables (and partitioned parents)
 *   --out-ops        `CREATE INDEX CONCURRENTLY IF NOT EXISTS` for LARGE/unknown-size tables; run by hand with
 *                    psql (autocommit). Never wrap it in BEGIN…COMMIT and never put it in supabase/migrations.
 * Options: --concurrent-above 100000 (reltuples)  --tables a,b  --schema public  --dry-run
 */
import { readFileSync, writeFileSync } from "node:fs";
import { planIndexes } from "./rls-perf-lib.mjs";

const q = (s) => `"${s.replace(/"/g, '""')}"`;

export function renderMigration(items) {
  return `-- Vireek: indexes for RLS policy columns (small tables; idempotent).
-- Generated by scripts/security/rls-index-generator.mjs. Large tables are handled by supabase/ops/rls_indexes_concurrently.sql
-- because CREATE INDEX CONCURRENTLY cannot run inside a transaction.
-- ${items.length} indexes. A plain CREATE INDEX blocks writes on the table while it builds; these tables are small.
${items.map((i) => `create index if not exists ${q(i.name)} on public.${q(i.table)} (${q(i.column)});${i.partitioned ? " -- partitioned parent: builds on every partition" : ""}`).join("\n")}
`;
}

export function renderOps(items) {
  return `-- Vireek: RLS policy-column indexes for LARGE / unknown-size tables.
-- RUN MANUALLY, outside any transaction:   psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 -f supabase/ops/rls_indexes_concurrently.sql
-- (psql autocommit; do NOT add BEGIN/COMMIT, do NOT move this file into supabase/migrations.)
-- Each statement is idempotent, but a FAILED concurrent build leaves an INVALID index that IF NOT EXISTS will
-- then skip. After the run execute the check at the bottom; drop any invalid index and re-run.
\\set ON_ERROR_STOP on
${items.map((i) => `create index concurrently if not exists ${q(i.name)} on public.${q(i.table)} (${q(i.column)}); -- ~${i.reltuples < 0 ? "unknown" : i.reltuples} rows`).join("\n")}

-- Post-check (must return 0 rows):
select c.relname as invalid_index from pg_index i join pg_class c on c.oid = i.indexrelid
 where not i.indisvalid and c.relname in (${items.map((i) => `'${i.name}'`).join(", ")});
-- If a row appears:  drop index concurrently public."<that name>";  then re-run this file.
`;
}

function parseArgs(argv) {
  const o = { schema: "public", concurrentAbove: 100000 };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--dry-run") o.dry = true;
    else if (argv[i].startsWith("--")) o[argv[i].slice(2).replace(/-(\w)/g, (_, c) => c.toUpperCase())] = argv[++i];
  }
  o.concurrentAbove = Number(o.concurrentAbove);
  return o;
}

function main() {
  const o = parseArgs(process.argv.slice(2));
  if (!o.catalog) { console.error("Missing --catalog <rls-catalog.json>"); process.exit(2); }
  const cat = JSON.parse(readFileSync(o.catalog, "utf8"));
  const tables = o.tables ? o.tables.split(",").map((s) => s.trim()).filter(Boolean) : null;
  const items = planIndexes(cat, { tables, schema: o.schema, concurrentAbove: o.concurrentAbove });
  const small = items.filter((i) => !i.concurrent);
  const big = items.filter((i) => i.concurrent);
  console.error(`missing policy-column indexes: ${items.length} (migration: ${small.length}, concurrent/manual: ${big.length})`);
  if (o.dry) return;
  if (o.outMigration && small.length) { writeFileSync(o.outMigration, renderMigration(small)); console.error(`wrote ${o.outMigration}`); }
  if (o.outOps && big.length) { writeFileSync(o.outOps, renderOps(big)); console.error(`wrote ${o.outOps}`); }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
