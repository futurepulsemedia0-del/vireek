#!/usr/bin/env node
/**
 * Vireek — RLS initPlan wrap generator.
 *
 * Rewrites policy expressions so auth.uid()/auth.jwt()/auth.role()/auth.email() are evaluated ONCE per
 * statement (an initPlan) instead of once per row:  auth.uid()  ->  (select auth.uid()).
 * The generator reads the LIVE catalog (pg_policies), never the migration text, because ALTER POLICY must
 * restate the exact deployed expression.
 *
 * Usage:
 *   psql "$DATABASE_URL" -X -At -f scripts/security/rls-catalog-export.sql > rls-catalog.json
 *   node scripts/security/rls-wrap-generator.mjs --catalog rls-catalog.json --top 20 \
 *        --out-migration supabase/migrations/<VERSION>_rls_initplan_wrap_batch1.sql \
 *        --out-test      supabase/tests/database/rls_initplan_wrap_batch1.test.sql \
 *        --out-rollback  supabase/ops/rls_initplan_wrap_batch1.rollback.sql
 * Options: --tables a,b,c (explicit list, overrides --top)  --schema public  --owner-fn off (do not wrap get_account_owner_id())  --dry-run
 * Output is deterministic for a given catalog file. Nothing is executed against any database.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { OWNER_FN, SQL_BARE, SQL_WRAPPED, dq, md5, normalizedHash, pickTargets, planPolicies, sha256, sqlStr } from "./rls-perf-lib.mjs";

const PAT_WRAPPED = SQL_WRAPPED;
const PAT_BARE = SQL_BARE;
// SQL regex matching a '…' string literal (with '' escapes); literals are blanked before counting calls.
const PAT_LIT = String.raw`''([^'']|'''')*''`;
// unwrap(x): (select f() as f) -> f(), and drop the `public.` qualifier of get_account_owner_id — same as unwrapAuthCalls().
const unw = (x) => `regexp_replace(regexp_replace(coalesce(${x}, ''), '${PAT_WRAPPED}', '\\1()', 'gi'), 'public\\.get_account_owner_id', 'get_account_owner_id', 'gi')`;
const nolit = (x) => `regexp_replace(${x}, '${PAT_LIT}', '_', 'g')`;
const cnt = (x, pat) => `(select count(*) from regexp_matches(${x}, '${pat}', 'gi'))`;

const val = (p) =>
  `    (${sqlStr(p.table)}, ${sqlStr(p.policy)}, ${sqlStr(normalizedHash(p.origUsing))}, ${sqlStr(normalizedHash(p.origCheck))}, ` +
  `${p.newUsing == null ? "null::text" : dq("q", p.newUsing)}, ${p.newCheck == null ? "null::text" : dq("q", p.newCheck)})`;

export function renderMigration(plan, meta) {
  const tables = [...new Set(plan.map((p) => p.table))];
  return `-- Vireek: RLS initPlan wrap — batch ${meta.batch}
-- Wraps auth.uid()/auth.jwt()/auth.role()/auth.email() as (select auth.<fn>()) in ${plan.length} policies on ${tables.length} tables.
-- BEHAVIOUR-PRESERVING: only the evaluation strategy changes (once per statement instead of once per row);
-- auth.* are STABLE and read request.jwt.claims, which is constant within a statement.
-- Tables: ${tables.join(", ")}
-- Generated by scripts/security/rls-wrap-generator.mjs from a catalog export (sha256 ${meta.catalogSha.slice(0, 16)}…).
--
-- Safety:
--  * Idempotent. A policy is altered only if (a) it still exists, (b) its expression, modulo wrapping, is
--    identical to the one captured at generation time (md5), and (c) it still has unwrapped calls.
--    Otherwise it is skipped with a NOTICE — never overwritten blindly.
--  * ALTER POLICY takes a strong table lock (see docs/security/rls-initplan-wrap.md). lock_timeout makes a busy
--    table fail fast; just re-run the migration (it is idempotent).
--  * Rollback: supabase/ops/rls_initplan_wrap_batch${meta.batch}.rollback.sql

do $rlsw$
declare
  r        record;
  cur      record;
  v_u      text;
  v_c      text;
  v_left   int;
  v_done   int := 0;
  v_skip   int := 0;
begin
  perform set_config('lock_timeout', '10s', true);

  for r in
    select * from (values
${plan.map(val).join(",\n")}
    ) as v(tbl, pol, q_hash, c_hash, new_using, new_check)
  loop
    select p.qual, p.with_check into cur
      from pg_policies p
     where p.schemaname = 'public' and p.tablename = r.tbl and p.policyname = r.pol;
    if not found then
      raise notice 'rls-wrap: skip % on % (policy not found)', r.pol, r.tbl; v_skip := v_skip + 1; continue;
    end if;

    if md5(${unw('cur.qual')}) is distinct from r.q_hash
       or md5(${unw('cur.with_check')}) is distinct from r.c_hash then
      raise notice 'rls-wrap: skip % on % (expression changed since capture — regenerate)', r.pol, r.tbl; v_skip := v_skip + 1; continue;
    end if;

    -- bare calls left = all calls (after unwrapping) minus calls already inside (select …)
    select ${cnt(nolit(unw('cur.qual')), PAT_BARE)} + ${cnt(nolit(unw('cur.with_check')), PAT_BARE)}
         - ${cnt(nolit("coalesce(cur.qual, '')"), PAT_WRAPPED)} - ${cnt(nolit("coalesce(cur.with_check, '')"), PAT_WRAPPED)}
      into v_left;
    if v_left = 0 then continue; end if; -- already applied

    v_u := case when r.new_using is not null then format(' using (%s)', r.new_using) else '' end;
    v_c := case when r.new_check is not null then format(' with check (%s)', r.new_check) else '' end;
    execute format('alter policy %I on public.%I%s%s', r.pol, r.tbl, v_u, v_c);
    v_done := v_done + 1;
  end loop;

  raise notice 'rls-wrap batch ${meta.batch}: altered %, skipped %', v_done, v_skip;
end
$rlsw$;
`;
}

export function renderRollback(plan, meta) {
  const rows = plan.map((p) => `    (${sqlStr(p.table)}, ${sqlStr(p.policy)}, ${p.newUsing == null ? "null::text" : dq("o", p.origUsing)}, ${p.newCheck == null ? "null::text" : dq("o", p.origCheck)})`);
  return `-- Vireek: ROLLBACK for RLS initPlan wrap batch ${meta.batch} (run manually with psql; not a migration).
-- Restores the expression text captured at generation time. Policies that no longer exist are skipped.
do $rlsw_rb$
declare r record;
begin
  perform set_config('lock_timeout', '10s', true);
  for r in select * from (values
${rows.join(",\n")}
  ) as v(tbl, pol, orig_using, orig_check)
  loop
    if exists (select 1 from pg_policies where schemaname = 'public' and tablename = r.tbl and policyname = r.pol) then
      execute format('alter policy %I on public.%I%s%s', r.pol, r.tbl,
        case when r.orig_using is not null then format(' using (%s)', r.orig_using) else '' end,
        case when r.orig_check is not null then format(' with check (%s)', r.orig_check) else '' end);
    end if;
  end loop;
end
$rlsw_rb$;
`;
}

export function renderTest(plan, meta) {
  const rows = plan.map((p) => `  (${sqlStr(p.table)}, ${sqlStr(p.policy)}, ${sqlStr(p.cmd)}, ${sqlStr(p.permissive)}, ${sqlStr(p.roles)}, ${sqlStr(normalizedHash(p.origUsing))}, ${sqlStr(normalizedHash(p.origCheck))}, ${p.newUsing != null}, ${p.newCheck != null})`);
  const U = unw('p.qual');
  const C = unw('p.with_check');
  return `-- pgTAP (generated): structural proof that RLS initPlan wrap batch ${meta.batch} changed ONLY the evaluation strategy.
-- Run AFTER the migration.  Behavioural proof on sample roles: rls_initplan_equivalence.test.sql and
-- scripts/security/rls-wrap-equivalence.sql (before/after row fingerprints on the real tables).
begin;
select plan(4);

create temp table _rlsw_expected (tbl text, pol text, cmd text, permissive text, roles text, q_hash text, c_hash text, has_u boolean, has_c boolean) on commit drop;
insert into _rlsw_expected values
${rows.join(",\n")};

select is_empty($$ select e.tbl, e.pol from _rlsw_expected e
  where not exists (select 1 from pg_policies p where p.schemaname='public' and p.tablename=e.tbl and p.policyname=e.pol) $$,
  'every targeted policy still exists');

select is_empty($$ select e.tbl, e.pol from _rlsw_expected e join pg_policies p on p.schemaname='public' and p.tablename=e.tbl and p.policyname=e.pol
  where md5(${U}) <> e.q_hash or md5(${C}) <> e.c_hash $$,
  'expressions equal the originals modulo (select auth.*()) wrapping');

select is_empty($$ select e.tbl, e.pol from _rlsw_expected e join pg_policies p on p.schemaname='public' and p.tablename=e.tbl and p.policyname=e.pol
  where ${cnt(nolit(unw('p.qual')), PAT_BARE)} + ${cnt(nolit(unw('p.with_check')), PAT_BARE)}
      - ${cnt(nolit("coalesce(p.qual,'')"), PAT_WRAPPED)} - ${cnt(nolit("coalesce(p.with_check,'')"), PAT_WRAPPED)} <> 0 $$,
  'no unwrapped auth.*() remains in the targeted policies');

select is_empty($$ select e.tbl, e.pol from _rlsw_expected e join pg_policies p on p.schemaname='public' and p.tablename=e.tbl and p.policyname=e.pol
  where lower(p.cmd) <> e.cmd or upper(p.permissive) <> e.permissive or array_to_string(p.roles, ',') <> e.roles $$,
  'command, permissive/restrictive and roles are unchanged');

select * from finish();
rollback;
`;
}

function parseArgs(argv) {
  const o = { top: 20, schema: "public" };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--dry-run") o.dry = true;
    else if (a.startsWith("--")) o[a.slice(2).replace(/-(\w)/g, (_, c) => c.toUpperCase())] = argv[++i];
  }
  o.top = Number(o.top);
  return o;
}

function main() {
  const o = parseArgs(process.argv.slice(2));
  if (!o.catalog) { console.error("Missing --catalog <rls-catalog.json> (see header for the export command)."); process.exit(2); }
  const raw = readFileSync(o.catalog, "utf8");
  const cat = JSON.parse(raw);
  const explicit = o.tables ? o.tables.split(",").map((s) => s.trim()).filter(Boolean) : null;
  const vol = cat.functions?.[OWNER_FN];
  const owner = o.ownerFn !== "off" && (vol === "s" || vol === "i");
  if (o.ownerFn !== "off" && !owner) console.error(`⚠ ${OWNER_FN}() not wrapped: catalog volatility is ${vol ?? "unknown (re-export the catalog)"}; it must be STABLE/IMMUTABLE.`);
  const targets = pickTargets(cat.policies, cat.stats, { top: o.top, explicit, schema: o.schema, owner });
  const plan = planPolicies(cat.policies, { schema: o.schema, tables: targets, owner });
  const total = planPolicies(cat.policies, { schema: o.schema, owner }).length;
  console.error(`catalog: ${cat.policies.length} policies, ${total} with unwrapped auth calls (all tables)`);
  console.error(`batch:   ${targets.length} tables, ${plan.length} policies, ${plan.reduce((n, p) => n + p.calls, 0)} calls to wrap`);
  for (const t of targets) console.error(`  - ${t} (${plan.filter((p) => p.table === t).length} policies)`);
  if (o.dry || !plan.length) return;
  const meta = { batch: o.batch ?? "1", catalogSha: sha256(raw) };
  const out = [[o.outMigration, renderMigration(plan, meta)], [o.outTest, renderTest(plan, meta)], [o.outRollback, renderRollback(plan, meta)]];
  for (const [file, body] of out) if (file) { writeFileSync(file, body); console.error(`wrote ${file}`); }
  void md5;
}

if (import.meta.url === `file://${process.argv[1]}`) main();
