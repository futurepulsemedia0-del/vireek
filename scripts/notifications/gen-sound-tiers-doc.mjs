// Regenerates docs/notifications/sound-tiers.md from soundTiers.ts (the single source of truth).
// Run: node --experimental-strip-types --no-warnings scripts/notifications/gen-sound-tiers-doc.mjs
import { writeFileSync } from "node:fs";
import { SOUND_TIERS, TIER_BY_PREFIX, TIER_BY_TYPE, TIER_CONFIG, TIER_RATIONALE, ANDROID_V2_CHANNELS_MIN_VERSION } from "../../supabase/functions/_shared/notify/soundTiers.ts";

const order = Object.fromEntries(SOUND_TIERS.map((t, i) => [t, i]));
const rows = Object.entries(TIER_BY_TYPE)
  .sort(([a, ta], [b, tb]) => order[ta] - order[tb] || a.localeCompare(b))
  .map(([type, tier]) => `| \`${type}\` | ${tier} | ${TIER_RATIONALE[type]} |`);
const prefixRows = Object.entries(TIER_BY_PREFIX).map(([p, v]) => `| \`${p}*\` | ${v.tier} | ${v.why} |`);

const tierRows = SOUND_TIERS.map((t) => {
  const c = TIER_CONFIG[t];
  return `| ${t} | \`${c.androidChannel}\` (\`${c.legacyAndroidChannel}\`) | ${c.androidImportance} | ${c.iosSound ?? "no sound (key omitted)"} | ${c.interruptionLevel}${c.interruptionLevel === "time-sensitive" ? " (if the person allows it, else active)" : ""} | ${c.haptic} | ${c.webSilent ? "silent: true" : "normal"} |`;
});

const md = `# Notification sound tiers

<!-- GENERATED by scripts/notifications/gen-sound-tiers-doc.mjs from supabase/functions/_shared/notify/soundTiers.ts. Do not edit the tables by hand. -->

Every push gets one of five tiers. The tier decides the Android channel, the iOS sound and interruption level, the
haptic, and whether web push is silent. System sounds only: the app ships no audio file.

## Tiers

| Tier | Android channel (legacy id for old apps) | Android importance | iOS sound | iOS interruption level | Haptic | Web push |
| --- | --- | --- | --- | --- | --- | --- |
${tierRows.join("\n")}

Android sounds: emergency uses the system default **ringtone** (USAGE_NOTIFICATION_RINGTONE); alert, normal and message use
the system default **notification** sound; quiet has no sound and no vibration.

## Type to tier

Unknown types fall back to **normal** at runtime. \`soundTiers.test.mjs\` fails the build when the code can emit a type
that is not listed below, so new notification types must be added to \`soundTiers.ts\` and this file regenerated.

| Type | Tier | Rationale |
| --- | --- | --- |
${rows.join("\n")}

Dynamic type families:

| Prefix | Tier | Rationale |
| --- | --- | --- |
${prefixRows.join("\n")}

## Rules and limits

- **Android: channel sound is immutable.** After a channel exists, only the person can change its sound or importance.
  To change a tier's sound, create a new channel id (bump the \`_v2\` suffix) in \`VireekNotificationChannels.java\` and
  \`soundTiers.ts\` together. Old channels stay until you know no installed build can still be sent to them: a push to a
  missing channel silently falls back to the default channel.
- **Old app builds.** The server sends the \`_v2\` id only to devices whose \`device_push_tokens.app_version\` is at least
  \`${ANDROID_V2_CHANNELS_MIN_VERSION}\` (\`ANDROID_V2_CHANNELS_MIN_VERSION\`). Unknown or older versions keep the legacy ids.
- **iOS cannot pick a system sound by name.** The only choices are "default" and no sound (omit \`sound\`). Critical Alerts are
  **not** used (entitlement not requested). Time-sensitive is used for emergency and alert only, and only when
  \`user_mobile_surface_prefs.time_sensitive_enabled\` is true.
- **Web push cannot play a custom or chosen sound.** The only control is \`silent: true\` (quiet tier), applied in \`public/sw.js\`.
- **Per-person override.** \`user_mobile_surface_prefs.sound_off_tiers\` (text[]) turns a tier's sound off for that person:
  iOS omits \`sound\`, Android uses the quiet channel (Android cannot mute one message on a loud channel), web sends
  \`silent: true\`. There is no settings screen for it yet; the column is honoured server-side for native devices. Web
  subscriptions use the tier default.
- **Foreground.** \`capacitor.config.ts\` keeps \`presentationOptions: ['badge','sound','alert']\`. iOS plays a foreground sound only
  if the payload has one, so quiet stays silent. On Android the plugin's foreground behaviour for the quiet channel has not
  been verified: test it on a device.
- **Team chat** (\`send-chat-push\`) is web push only today (no FCM path), so the message tier reaches native devices only
  for \`comment_*\` / \`job_message\` notifications that go through \`send-push-notification\`.
- Live-call ongoing notifications (\`live-surface-dispatch\`) use the emergency channel for emergencies and the normal
  channel otherwise. The Live Activity APNs payload (\`apns.ts\`) is unchanged.

## Manual verification (not covered by automated tests)

See the checklist in the delivery notes: real Android (8+, a device below the v2 version, DND and channel settings) and a
real iPhone (default sound, Focus and Time Sensitive, passive quiet, foreground behaviour).
`;
writeFileSync(new URL("../../docs/notifications/sound-tiers.md", import.meta.url), md);
console.log("wrote docs/notifications/sound-tiers.md", rows.length, "types");
