#!/usr/bin/env node
// scripts/governance/check-runbooks.mjs
//
// Lists runbooks / security docs that have no owner or whose test is stale, and validates their frontmatter.
//
//   node scripts/governance/check-runbooks.mjs                 report; exit 1 only for INVALID frontmatter
//   node scripts/governance/check-runbooks.mjs --strict        ownerless / never-tested / stale also exit 1 (release branches)
//   node scripts/governance/check-runbooks.mjs --today 2027-03-01   pretend today is that UTC date
//   node scripts/governance/check-runbooks.mjs --max-age-days 180   "stale" threshold for last_tested (default 365)
//   node scripts/governance/check-runbooks.mjs --json               machine-readable result on stdout
//   node scripts/governance/check-runbooks.mjs --report-file out.md Markdown report (also appended to $GITHUB_STEP_SUMMARY)
//
// Frontmatter contract (first lines of every scanned .md):
//   ---
//   owner: TBD                 # a person or role. TBD / empty = ownerless
//   kind: runbook              # runbook | playbook | reference | template | log
//   area: voice                # optional: security|voice|billing|integrations|support|compliance|unassigned (docs/OWNERS.md)
//   last_tested: never         # runbook/playbook: YYYY-MM-DD or "never".  Other kinds: "n/a"
//   next_test: TBD             # runbook/playbook: YYYY-MM-DD or "TBD".    Other kinds: "n/a"
//   evidence: docs/...         # REQUIRED when last_tested is a date: repo path that exists, or an https URL
//   ---
//
// What this proves: the metadata is well formed, nobody claims a test without evidence, and dates have not lapsed.
// What it does NOT prove: that a drill really happened or that a runbook works. Only a person running it does.
// Generated files (docs/security/function-matrix.md, rls-audit.md) are skipped: their generators overwrite the file.
//
// Exit codes: 0 ok (warnings may be listed) | 1 invalid frontmatter, or --strict and something to report | 2 bad usage.

import { existsSync, readdirSync, readFileSync, statSync, appendFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = resolve(HERE, '..', '..');

export const SCAN_DIRS = Object.freeze(['docs/runbooks', 'docs/security']);
/** Generated by a script that rewrites the whole file; frontmatter would be wiped and its --check would go stale. */
export const GENERATED = Object.freeze(['docs/security/function-matrix.md', 'docs/security/rls-audit.md']);
export const KINDS = Object.freeze(['runbook', 'playbook', 'reference', 'template', 'log']);
export const TESTABLE_KINDS = Object.freeze(['runbook', 'playbook']);
export const AREAS = Object.freeze(['security', 'voice', 'billing', 'integrations', 'support', 'compliance', 'unassigned']);
export const DEFAULT_MAX_AGE_DAYS = 365;

const KEYS = new Set(['owner', 'kind', 'area', 'last_tested', 'next_test', 'evidence']);
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const OWNER_PLACEHOLDER_RE = /^(tbd|todo|unassigned|none|n\/a|-|—)$/i;

// ---------------------------------------------------------------- dates (UTC, day precision)

/** 'YYYY-MM-DD' -> days since epoch, or null when it is not a real calendar date. */
export function dayNumber(s) {
  if (typeof s !== 'string' || !DATE_RE.test(s)) return null;
  const [y, m, d] = s.split('-').map(Number);
  const t = Date.UTC(y, m - 1, d);
  const back = new Date(t);
  if (back.getUTCFullYear() !== y || back.getUTCMonth() !== m - 1 || back.getUTCDate() !== d) return null;
  return Math.round(t / 86_400_000);
}
export const todayUtc = () => new Date().toISOString().slice(0, 10);

// ---------------------------------------------------------------- frontmatter

/**
 * Minimal, strict parser for the flat `key: value` subset used here (no nesting, no multiline).
 * Returns { data, error, body } — `data` is null when there is no frontmatter block at all.
 */
export function parseFrontmatter(text) {
  const src = text.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  if (!src.startsWith('---\n')) return { data: null, error: null, body: src };
  const end = src.indexOf('\n---', 4);
  if (end === -1) return { data: null, error: 'frontmatter block is not closed with ---', body: src };
  const after = src.slice(end + 4);
  if (after !== '' && !after.startsWith('\n')) return { data: null, error: 'closing --- must be on its own line', body: src };
  const data = {};
  for (const [i, raw] of src.slice(4, end).split('\n').entries()) {
    if (raw.trim() === '' || raw.trim().startsWith('#')) continue;
    const m = raw.match(/^([a-z_]+):[ \t]*(.*)$/);
    if (!m) return { data: null, error: `frontmatter line ${i + 1} is not "key: value"`, body: src };
    let v = m[2].replace(/[ \t]+#.*$/, '').trim();
    if (/^(["']).*\1$/.test(v)) v = v.slice(1, -1);
    if (Object.hasOwn(data, m[1])) return { data: null, error: `duplicate key "${m[1]}"`, body: src };
    data[m[1]] = v;
  }
  return { data, error: null, body: after.replace(/^\n/, '') };
}

export const isOwnerless = (owner) => typeof owner !== 'string' || owner.trim() === '' || OWNER_PLACEHOLDER_RE.test(owner.trim());

function isSafeRepoPath(p) {
  if (!p || isAbsolute(p) || p.includes('\\') || p.includes('\0')) return false;
  return !p.split('/').some((seg) => seg === '..' || seg === '');
}

// ---------------------------------------------------------------- evaluation of one document

/**
 * @returns {{ file, kind, owner, invalid: string[], findings: string[] }}
 *   invalid  = malformed metadata (always fails the check)
 *   findings = ownerless / never tested / stale / overdue / unscheduled (fail only with --strict)
 */
export function evaluateDoc(file, text, { today = todayUtc(), maxAgeDays = DEFAULT_MAX_AGE_DAYS, root = REPO_ROOT } = {}) {
  const out = { file, kind: null, owner: null, invalid: [], findings: [] };
  const { data, error } = parseFrontmatter(text);
  if (error) { out.invalid.push(error); return out; }
  if (!data) { out.invalid.push('no frontmatter (add owner, kind, last_tested, next_test)'); return out; }

  for (const k of Object.keys(data)) if (!KEYS.has(k)) out.invalid.push(`unknown key "${k}"`);
  out.owner = data.owner ?? null;
  out.kind = data.kind ?? null;

  if (!KINDS.includes(data.kind)) out.invalid.push(`kind must be one of ${KINDS.join(' | ')}`);
  if (data.area !== undefined && !AREAS.includes(data.area)) out.invalid.push(`area must be one of ${AREAS.join(' | ')}`);
  if (data.owner === undefined) out.invalid.push('missing key "owner" (use TBD if nobody owns it yet)');
  if (data.last_tested === undefined) out.invalid.push('missing key "last_tested"');
  if (data.next_test === undefined) out.invalid.push('missing key "next_test"');
  if (out.invalid.length) return out;

  const testable = TESTABLE_KINDS.includes(data.kind);
  const todayN = dayNumber(today);
  const lastN = dayNumber(data.last_tested);
  const nextN = dayNumber(data.next_test);

  if (isOwnerless(data.owner)) out.findings.push('ownerless');

  if (!testable) {
    if (data.last_tested !== 'n/a' && lastN === null) out.invalid.push(`last_tested must be YYYY-MM-DD or n/a for kind "${data.kind}"`);
    if (data.next_test !== 'n/a' && nextN === null) out.invalid.push(`next_test must be YYYY-MM-DD or n/a for kind "${data.kind}"`);
  } else {
    if (data.last_tested !== 'never' && lastN === null) out.invalid.push('last_tested must be YYYY-MM-DD or "never"');
    if (data.next_test !== 'TBD' && nextN === null) out.invalid.push('next_test must be YYYY-MM-DD or "TBD"');
  }

  if (lastN !== null) {
    if (todayN !== null && lastN > todayN) out.invalid.push('last_tested is in the future');
    // No test claim without proof: a date needs evidence that a reader can open.
    const ev = data.evidence;
    if (!ev) out.invalid.push('last_tested is a date but "evidence" is missing (repo path or https URL of the drill record)');
    else if (/^https:\/\/\S+$/.test(ev)) { /* external record; cannot be checked offline */ }
    else if (!isSafeRepoPath(ev)) out.invalid.push('evidence must be a repo-relative path without ".." or an https URL');
    else if (!existsSync(join(root, ev))) out.invalid.push(`evidence path does not exist: ${ev}`);
  }
  if (lastN !== null && nextN !== null && nextN < lastN) out.invalid.push('next_test is before last_tested');
  if (out.invalid.length) return out;

  if (testable) {
    if (data.last_tested === 'never') out.findings.push('never tested');
    else if (todayN !== null && todayN - lastN > maxAgeDays) out.findings.push(`stale: last tested ${todayN - lastN} days ago (limit ${maxAgeDays})`);
    if (data.next_test === 'TBD') out.findings.push('no next test scheduled');
    else if (todayN !== null && nextN < todayN) out.findings.push(`overdue: next test was due ${data.next_test}`);
  }
  return out;
}

// ---------------------------------------------------------------- repo scan

export function listDocs(root = REPO_ROOT) {
  const files = [];
  const walk = (dir) => {
    const abs = join(root, dir);
    if (!existsSync(abs)) return;
    for (const name of readdirSync(abs).sort()) {
      const rel = `${dir}/${name}`;
      const st = statSync(join(root, rel));
      if (st.isDirectory()) walk(rel);
      else if (name.toLowerCase().endsWith('.md') && !GENERATED.includes(rel)) files.push(rel);
    }
  };
  for (const d of SCAN_DIRS) walk(d);
  return files;
}

export function runCheck({ root = REPO_ROOT, today = todayUtc(), maxAgeDays = DEFAULT_MAX_AGE_DAYS } = {}) {
  const results = listDocs(root).map((f) => evaluateDoc(f, readFileSync(join(root, f), 'utf8'), { today, maxAgeDays, root }));
  const invalid = results.filter((r) => r.invalid.length);
  const flagged = results.filter((r) => !r.invalid.length && r.findings.length);
  return { today, maxAgeDays, scanned: results.length, invalid, flagged, ownerless: results.filter((r) => r.findings.includes('ownerless')).length, results };
}

export function renderReport(res) {
  const L = [`# Runbook ownership report (${res.today})`, '', `Scanned ${res.scanned} files in ${SCAN_DIRS.join(', ')}. Skipped generated: ${GENERATED.join(', ')}.`, ''];
  L.push(`- Invalid frontmatter: **${res.invalid.length}**`, `- Ownerless: **${res.ownerless}**`, `- With at least one finding: **${res.flagged.length}**`, '');
  if (res.invalid.length) {
    L.push('## Invalid', '', '| File | Problem |', '|---|---|');
    for (const r of res.invalid) L.push(`| \`${r.file}\` | ${r.invalid.join('; ')} |`);
    L.push('');
  }
  if (res.flagged.length) {
    L.push('## Ownerless or stale', '', '| File | Kind | Owner | Findings |', '|---|---|---|---|');
    for (const r of res.flagged) L.push(`| \`${r.file}\` | ${r.kind} | ${r.owner || '—'} | ${r.findings.join('; ')} |`);
    L.push('');
  }
  L.push('_A listed runbook is a reminder, not a verdict. This check cannot tell whether a drill really happened._');
  return `${L.join('\n')}\n`;
}

// ---------------------------------------------------------------- CLI

function parseArgs(argv) {
  const o = { strict: false, json: false, today: todayUtc(), maxAgeDays: DEFAULT_MAX_AGE_DAYS, reportFile: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--strict') o.strict = true;
    else if (a === '--json') o.json = true;
    else if (a === '--today') o.today = argv[++i];
    else if (a === '--max-age-days') o.maxAgeDays = Number(argv[++i]);
    else if (a === '--report-file') o.reportFile = argv[++i];
    else throw new Error(`unknown argument: ${a}`);
  }
  if (dayNumber(o.today) === null) throw new Error('--today must be a real YYYY-MM-DD date');
  if (!Number.isInteger(o.maxAgeDays) || o.maxAgeDays < 1 || o.maxAgeDays > 3650) throw new Error('--max-age-days must be an integer 1..3650');
  if (o.reportFile !== null && !o.reportFile) throw new Error('--report-file needs a path');
  return o;
}

function main() {
  let opts;
  try { opts = parseArgs(process.argv.slice(2)); } catch (e) { console.error(`check-runbooks: ${e.message}`); return 2; }
  const res = runCheck({ today: opts.today, maxAgeDays: opts.maxAgeDays });
  const report = renderReport(res);

  if (opts.json) console.log(JSON.stringify({ today: res.today, scanned: res.scanned, invalid: res.invalid, flagged: res.flagged }, null, 2));
  else {
    for (const r of res.invalid) console.log(`::error file=${r.file}::${r.invalid.join('; ')}`);
    const level = opts.strict ? 'error' : 'warning';
    for (const r of res.flagged) console.log(`::${level} file=${r.file}::${r.findings.join('; ')}`);
    console.log(`Runbook ownership: ${res.scanned} scanned, ${res.invalid.length} invalid, ${res.ownerless} ownerless, ${res.flagged.length} with findings.`);
  }
  if (opts.reportFile) writeFileSync(resolve(opts.reportFile), report);
  if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, report);

  if (res.invalid.length) return 1;
  return opts.strict && res.flagged.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
