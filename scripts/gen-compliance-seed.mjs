#!/usr/bin/env node
// Regenerates supabase/migrations/20271110000100_compliance_rule_seed.sql from the
// canonical starter catalog. Run: node --experimental-strip-types scripts/gen-compliance-seed.mjs
// Seeded versions are "in_review": nothing is enforced until staff approve them.
import { writeFileSync } from 'node:fs';
import { SEED_RULES, SEED_EFFECTIVE_FROM } from '../supabase/functions/_shared/compliance-rules/seedRules.ts';

const rows = SEED_RULES.map((r) => JSON.stringify(r)).join(',\n');
const sql = `-- GENERATED by scripts/gen-compliance-seed.mjs from supabase/functions/_shared/compliance-rules/seedRules.ts
-- Starter rule packs — drafted as a research starting point, NOT verified legal text.
-- Every version is seeded as 'in_review' and is never enforced until a staff reviewer
-- confirms the sources with counsel and approves it (Compliance → Rule review).
-- Idempotent: a rule that already has any version is left untouched.

DO $seed_do$
DECLARE
  r jsonb;
  v_pack uuid;
  v_rule uuid;
  v_ver uuid;
BEGIN
  FOR r IN SELECT * FROM jsonb_array_elements($seed$[
${rows}
]$seed$::jsonb) LOOP
    INSERT INTO public.compliance_packs (slug, name, jurisdiction)
    VALUES (r ->> 'packSlug', r ->> 'packName', r ->> 'jurisdiction')
    ON CONFLICT (slug) DO NOTHING;
    SELECT id INTO v_pack FROM public.compliance_packs WHERE slug = r ->> 'packSlug';

    INSERT INTO public.compliance_rules (pack_id, rule_key, kind)
    VALUES (v_pack, r ->> 'ruleKey', r ->> 'kind')
    ON CONFLICT (pack_id, rule_key) DO NOTHING;
    SELECT id INTO v_rule FROM public.compliance_rules WHERE pack_id = v_pack AND rule_key = r ->> 'ruleKey';

    IF NOT EXISTS (SELECT 1 FROM public.compliance_rule_versions WHERE rule_id = v_rule) THEN
      INSERT INTO public.compliance_rule_versions
        (rule_id, version, status, severity, applies_to, title, owner_explanation, params, source_refs,
         effective_from, authored_by_email, submitted_at)
      VALUES
        (v_rule, 1, 'in_review', r ->> 'severity',
         ARRAY(SELECT jsonb_array_elements_text(r -> 'appliesTo')),
         r ->> 'title', r ->> 'ownerExplanation', r -> 'params', r -> 'sourceRefs',
         DATE '${SEED_EFFECTIVE_FROM}', 'system@vireek', now())
      RETURNING id INTO v_ver;
      INSERT INTO public.compliance_review_events (version_id, action, from_status, to_status, notes, actor_email)
      VALUES (v_ver, 'seeded', NULL, 'in_review', 'Starter rule — needs counsel review before approval.', 'system@vireek');
    END IF;
  END LOOP;
END $seed_do$;
`;
writeFileSync('supabase/migrations/20271110000100_compliance_rule_seed.sql', sql);
console.log(`wrote ${SEED_RULES.length} rules`);
