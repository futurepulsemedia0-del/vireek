# Run from repo root: python3 scripts/docs/gen-catalogs.py
# Regenerates docs/generated/{EDGE_FUNCTIONS,WEBHOOKS,ENV_USAGE,CRON_JOBS,TABLES}.md by static scan.
import os;os.makedirs("docs/generated",exist_ok=True)
import re,os,json,glob,collections
OUT='docs/generated/'
FN='supabase/functions'
cfg=open('supabase/config.toml').read()
jwt={m.group(1):m.group(2) for m in re.finditer(r'\[functions\.([\w-]+)\]\s*\n\s*verify_jwt\s*=\s*(\w+)',cfg)}
dom={'Billing & payments':r'invoice|payment|payout|stripe|billing|subscription|split|statement|collections|dispute|terminal|sla-credit|tax|money|punchout|lien|pay-|wallet|plaid|capital',
'Accounting / CRM / ERP / payroll':r'^(acct|crm|qbo|ns-|intacct|payroll|supplier|fx-|gusto|xero|hubspot|jobber)',
'AI, voice & telephony':r'call|voice|dialer|pbx|proxy|csr|first-call|conversation|auto-reply|^ai-|operator|assistant|copilot|video-ice|live-call|ovb|vapi|agent|mcp|demo-chat|knowledge',
'Scheduling, jobs & field':r'job|dispatch|booking|recurring|closeout|daily|cadence|warranty|equipment|technician|rescue|quote|landing|schedule|appointment|route|estimate|project',
'Messaging & notifications':r'email|notif|message|push|resend|survey|feedback|lifecycle|chat|blog|sms|slack|teams|campaign|review|mail',
'Security, trust, privacy & data':r'security|trust|audit|compliance|impersonate|retention|subprocessor|delete|purge|rum-|findings|exit-|leak|homeowner|dsar|ip-|backup|dr-|data-|sso|scim|mfa|passkey|auth'}
def domain(n):
    for k,p in dom.items():
        if re.search(p,n):return k
    return 'Other'
rows=[];envmap={}
for n in sorted(os.listdir(FN)):
    d=f'{FN}/{n}'
    if n.startswith('_') or not os.path.isdir(d):continue
    idx=d+'/index.ts'
    src=open(idx,errors='ignore').read() if os.path.exists(idx) else ''
    if not src:
        rows.append(dict(n=n,idx=False,desc='(no index.ts)',jwt=jwt.get(n,'default'),env=[],sig='',cron=False,idem=False,dom=domain(n)));continue
    lines=src.split('\n');desc=''
    for l in lines[:12]:
        t=l.strip()
        if t.startswith(('//','/*','*')):
            t=t.lstrip('/* ').strip()
            if t and not t.startswith(('deno-lint','@ts','eslint','---','===')) and not re.match(r'^[\w./-]+\.(ts|tsx)$',t) and not re.match(r'^(supabase|functions)/',t):desc=t;break
    desc=desc.replace('|','\\|')[:140]
    env=sorted(set(re.findall(r"Deno\.env\.get\(\s*['\"]([A-Z0-9_]+)['\"]",src)))
    sig=[]
    if re.search(r'constructEvent|stripe-signature',src,re.I):sig.append('Stripe signature')
    if re.search(r'hmac|timingSafeEqual|x-[a-z-]*(signature|secret)',src,re.I):sig.append('HMAC/secret header')
    cron=bool(re.search(r'CRON_SECRET|x-cron|cron',src,re.I))
    idem=bool(re.search(r'idempoten|on conflict|upsert',src,re.I))
    rows.append(dict(n=n,idx=True,desc=desc,jwt=jwt.get(n,'default (true)'),env=env,sig=', '.join(sig),cron=cron,idem=idem,dom=domain(n)))
    envmap[n]=env
# EDGE_FUNCTIONS.md
o=['# Edge function catalog','','> Generated from `supabase/functions/*/index.ts` and `supabase/config.toml` by a static scan. "Purpose" is the first header comment (blank = no header comment; open the file). `verify_jwt` shows `supabase/config.toml` only; functions not listed there use the Supabase default.','',f'Total function folders: **{len(rows)}**. `verify_jwt = false` entries in config.toml: **{sum(1 for v in jwt.values() if v=="false")}** of {len(jwt)}.','',
'Columns: **Auth** = verify_jwt setting; **Guards** = signature/secret patterns detected by grep (not a security review); **Env** = `Deno.env.get` names.','']
by=collections.defaultdict(list)
for r in rows:by[r['dom']].append(r)
for k in sorted(by):
    o+=[f'## {k} ({len(by[k])})','','| Function | Purpose (header comment) | Auth | Guards | Env vars |','|---|---|---|---|---|']
    for r in by[k]:
        g=r['sig']+(' + cron secret' if r['cron'] and not r['sig'] else '')
        o.append(f"| `{r['n']}` | {r['desc'] or '—'} | {r['jwt']} | {g or '—'} | {', '.join('`'+e+'`' for e in r['env'][:6])}{' …' if len(r['env'])>6 else ''} |")
    o.append('')
open(OUT+'EDGE_FUNCTIONS.md','w').write('\n'.join(o))
# WEBHOOKS.md
w=[r for r in rows if re.search(r'webhook|events|sink|callback|-return|inbound|ingest',r['n'])]
o=['# Webhook & inbound endpoint catalog','','> Generated by static scan. Columns reflect patterns found in code (signature check, secret header, idempotency keywords). **Verify each against the provider docs before relying on it.** Retries are provider-controlled unless a function documents its own.','',f'Endpoints matched by name: **{len(w)}**.','','| Function | Auth (verify_jwt) | Signature / secret check detected | Idempotency keywords | Env vars |','|---|---|---|---|---|']
for r in w:o.append(f"| `{r['n']}` | {r['jwt']} | {r['sig'] or '**none detected — review**'} | {'yes' if r['idem'] else 'no'} | {', '.join('`'+e+'`' for e in r['env'][:5])} |")
o+=['','## Review rule','Every public (`verify_jwt = false`) endpoint must verify a provider signature or shared secret and must be safe to receive twice.','']
open(OUT+'WEBHOOKS.md','w').write('\n'.join(o))
# ENV_USAGE.md
usage=collections.defaultdict(set)
for n,e in envmap.items():
    for v in e:usage[v].add('edge:'+n)
for p,ex in (('src',('.ts','.tsx')),('packages',('.ts','.js','.mjs')),('chrome-extension',('.js',))):
    for root,_,fs in os.walk(p):
        if 'node_modules' in root:continue
        for f in fs:
            if f.endswith(ex):
                s=open(os.path.join(root,f),errors='ignore').read()
                for v in re.findall(r'import\.meta\.env\.([A-Z0-9_]+)',s):usage[v].add('web:'+p)
for p in ('scripts','e2e','load'):
    for root,_,fs in os.walk(p):
        for f in fs:
            s=open(os.path.join(root,f),errors='ignore').read()
            for v in re.findall(r'process\.env\.([A-Z0-9_]+)',s):usage[v].add('tooling:'+p)
for f in ('playwright.config.ts','vite.config.ts','capacitor.config.ts'):
    for v in re.findall(r'process\.env\.([A-Z0-9_]+)',open(f).read()):usage[v].add('tooling:'+f)
ed=open('ENVIRONMENT.md').read()+open('.env.example').read()
o=['# Environment variable usage (generated)','',f'> Generated by scanning code. **{len(usage)}** distinct variables. "In ENVIRONMENT.md/.env.example" = name appears there. Secret-looking names (KEY, SECRET, TOKEN, PASSWORD) must live only in Supabase secrets / CI secrets, never in the repo or `VITE_*`.','','| Variable | Where used | Documented | Secret-like |','|---|---|---|---|']
for v in sorted(usage):
    u=sorted(usage[v]);ws=', '.join(f'`{x[5:]}`' if x.startswith('edge:') else x for x in u[:4])+(f' (+{len(u)-4})' if len(u)>4 else '')
    sec='yes' if re.search(r'KEY|SECRET|TOKEN|PASSWORD|JWT',v) else ''
    bad=' **⚠ VITE_ exposes to browser**' if v.startswith('VITE_') and sec else ''
    o.append(f"| `{v}` | {ws} | {'yes' if v in ed else '**NO**'} | {sec}{bad} |")
open(OUT+'ENV_USAGE.md','w').write('\n'.join(o))

# CRON_JOBS.md
cr=collections.OrderedDict()
for f in sorted(glob.glob('supabase/migrations/*.sql')):
    s=open(f,errors='ignore').read()
    for m in re.finditer(r"cron\.schedule\(\s*'([^']+)'\s*,\s*'([^']+)'\s*,\s*(\$\$|')(.{0,200})",s,re.S):
        body=' '.join(m.group(4).split())[:90].replace('|','\\|')
        cr[m.group(1)]=(m.group(2),body,os.path.basename(f))
o=['# Scheduled jobs (pg_cron) catalog (generated)','',f'> Generated from `cron.schedule(...)` calls in migrations. **{len(cr)}** distinct job names. A migration may only *document* a schedule without installing it (some say scheduling is an operational choice) — check `select * from cron.job;` in each environment. Times are UTC. Failure handling: see `cron.job_run_details` and RUNBOOK §9.','','| Job | Schedule | Action (first 90 chars) | Defined in |','|---|---|---|---|']
for k,(s,b,f) in cr.items():o.append(f'| `{k}` | `{s}` | `{b}` | `{f}` |')
open(OUT+'CRON_JOBS.md','w').write('\n'.join(o))
# TABLES.md
tb=collections.OrderedDict();cm=set()
for f in sorted(glob.glob('supabase/migrations/*.sql')):
    s=open(f,errors='ignore').read()
    s=re.sub(r'(?m)^\s*--.*$','',s)
    for m in re.finditer(r'create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?(\w+)"?(?!\.|\w)',s,re.I):
        tb.setdefault(m.group(1),[os.path.basename(f),False])
    for m in re.finditer(r'enable\s+row\s+level\s+security',s,re.I):pass
    for m in re.finditer(r'alter\s+table\s+(?:only\s+)?(?:if\s+exists\s+)?(?:public\.)?"?(\w+)"?\s+enable\s+row\s+level\s+security',s,re.I):
        if m.group(1) in tb:tb[m.group(1)][1]=True
        else:tb.setdefault(m.group(1),['?',True])
    for m in re.finditer(r'comment\s+on\s+table\s+(?:public\.)?"?(\w+)"?',s,re.I):cm.add(m.group(1))
nr=[t for t,v in tb.items() if not v[1]]
o=['# Table catalog (generated)','',f'> NOTE: the distinct-table count can exceed the ~680 figure in ARCHITECTURE.md because this scan includes tables later dropped or renamed by other migrations; use `npm run db:audit` on a real database for the authoritative list. Static scan of `supabase/migrations/*.sql`. **{len(tb)}** distinct tables created; **{len(tb)-len(nr)}** have an `ENABLE ROW LEVEL SECURITY` statement found; **{len(cm)}** have `COMMENT ON TABLE`. A table listed as no-RLS may enable RLS in a way this regex misses (e.g. dynamic SQL) or may have been dropped later — verify with `scripts/db-audit` (`npm run db:audit`) against a real database.','','| Table | First created in | RLS statement found |','|---|---|---|']
for t,(f,r) in tb.items():o.append(f'| `{t}` | `{f}` | {"yes" if r else "**no**"} |')
open(OUT+'TABLES.md','w').write('\n'.join(o))

print(len(rows),len(w),len(usage),len(cr),len(tb),len(nr),len(cm))
