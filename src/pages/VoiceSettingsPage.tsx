/**
 * Voice - /dashboard/settings/voice
 * Audio Morning Brief (settings, sample voice, test button, player with transcript + captions + speed + "Why this?")
 * and "Call your Vireek" phone enrolment. All access rules are enforced server-side; this page only calls them.
 */
import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { Link } from 'react-router-dom';
import { useAuth } from '@/contexts/AuthContext';
import { useToast } from '@/contexts/ToastContext';
import { DashboardLayout } from '@/components/DashboardNav';
import {
  DEFAULT_VOICE_PREFS, activeWordIndex, enrollPhone, fetchLatestBrief, isE164, loadVoicePrefs, phoneStatus, playSample, previewBrief,
  removePhone, saveVoicePrefs, sendPhoneCode, type BriefView, type PhoneNumber, type VoicePrefs,
} from '@/lib/voiceBrief';

const SPEEDS = [0.8, 1, 1.25, 1.5];
const HOURS = Array.from({ length: 24 }, (_, h) => h);
const hourLabel = (h: number) => `${((h + 11) % 12) + 1}:00 ${h < 12 ? 'AM' : 'PM'}`;

function BriefPlayer({ brief, audioUrl, defaultSpeed }: { brief: BriefView; audioUrl: string | null; defaultSpeed: number }) {
  const ref = useRef<HTMLAudioElement>(null);
  const [speed, setSpeed] = useState(defaultSpeed);
  const [t, setT] = useState(0);
  const [dur, setDur] = useState(brief.audioSeconds ?? 0);
  const [why, setWhy] = useState(false);
  const words = useMemo(() => (brief.script ?? '').split(/\s+/).filter(Boolean), [brief.script]);
  const active = activeWordIndex(words.length, t, dur);
  useEffect(() => { if (ref.current) ref.current.playbackRate = speed; }, [speed, audioUrl]);

  return (
    <section aria-label="Morning brief player" className="rounded-xl border border-gray-200 p-4 space-y-3">
      <p className="text-sm text-gray-600">Brief for {brief.date} · {brief.wordCount ?? words.length} words · voice generated by AI</p>
      {audioUrl ? (
        <div className="flex flex-wrap items-center gap-3">
          <audio ref={ref} src={audioUrl} controls preload="none" className="min-w-0 flex-1"
            onTimeUpdate={(e) => setT(e.currentTarget.currentTime)} onLoadedMetadata={(e) => { setDur(e.currentTarget.duration); e.currentTarget.playbackRate = speed; }} />
          <label className="text-sm">Speed{' '}
            <select className="rounded border px-2 py-1" value={speed} onChange={(e) => setSpeed(Number(e.target.value))}>
              {SPEEDS.map((s) => <option key={s} value={s}>{s}×</option>)}
            </select>
          </label>
        </div>
      ) : (
        <p role="status" className="rounded bg-amber-50 p-3 text-sm text-amber-900">
          Audio isn't available for this brief{brief.delivered?.tts?.detail ? ` (${brief.delivered.tts.detail})` : ''}. Here is the text version.
        </p>
      )}
      <div aria-live="off" className="text-base leading-relaxed" data-testid="transcript">
        {words.map((w, i) => <span key={i} className={i === active ? 'rounded bg-yellow-200' : undefined}>{w} </span>)}
      </div>
      <p className="text-xs text-gray-500">Highlighting follows playback position and is approximate.</p>
      <button type="button" className="text-sm underline" aria-expanded={why} onClick={() => setWhy((v) => !v)}>Why this?</button>
      {why && (
        <ul className="space-y-1 text-sm" data-testid="evidence">
          {brief.evidence.length === 0 && <li>No supporting records were needed for this brief.</li>}
          {brief.evidence.map((e) => (
            <li key={e.key} className="flex flex-wrap justify-between gap-2">
              <span className="min-w-0">{e.label}: <strong>{String(e.value)}</strong></span>
              <Link to={e.href} className="underline">See records</Link>
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}

export function VoiceSettingsPage() {
  const { user, isOwner, teamMember, permissions } = useAuth();
  const { toast } = useToast();
  const ownerId = isOwner ? user?.id : (teamMember as { account_owner_id?: string } | null)?.account_owner_id;
  const allowed = isOwner || permissions.can_view_billing;
  const [prefs, setPrefs] = useState<VoicePrefs>(DEFAULT_VOICE_PREFS);
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const [brief, setBrief] = useState<{ brief: BriefView | null; audioUrl: string | null } | null>(null);
  const [sampleUrl, setSampleUrl] = useState<string | null>(null);
  const [numbers, setNumbers] = useState<PhoneNumber[]>([]);
  const [phone, setPhone] = useState('');
  const [codeSent, setCodeSent] = useState(false);
  const [code, setCode] = useState('');
  const [pin, setPin] = useState('');
  const set = <K extends keyof VoicePrefs>(k: K, v: VoicePrefs[K]) => setPrefs((p) => ({ ...p, [k]: v }));

  const refresh = useCallback(async () => {
    if (!user || !allowed) { setLoading(false); return; }
    try {
      const [p, b, n] = await Promise.all([loadVoicePrefs(user.id), fetchLatestBrief().catch(() => null), phoneStatus().catch(() => ({ numbers: [] }))]);
      if (p) setPrefs(p);
      setBrief(b);
      setNumbers(n.numbers);
    } catch { toast("We couldn't load your voice settings. Refresh to try again.", 'error'); }
    finally { setLoading(false); }
  }, [user, allowed, toast]);
  useEffect(() => { void refresh(); }, [refresh]);

  const run = async (name: string, fn: () => Promise<void>) => {
    setBusy(name);
    try { await fn(); } catch (e) { toast((e as Error).message, 'error'); } finally { setBusy(null); }
  };
  const save = async () => {
    if (!user || !ownerId) return;
    if (prefs.channel_whatsapp && !isE164(prefs.whatsapp_number ?? '')) { toast('Enter your WhatsApp number with the country code, like +14155550123.', 'error'); return; }
    setSaving(true);
    try { await saveVoicePrefs(user.id, ownerId, prefs); toast('Voice settings saved', 'success'); }
    catch { toast("We couldn't save your settings. Please try again.", 'error'); }
    finally { setSaving(false); }
  };

  if (!allowed) {
    return <DashboardLayout activeLabel="Voice"><p className="p-6">Voice features are available to owners and team members with billing access.</p></DashboardLayout>;
  }
  if (loading) return <DashboardLayout activeLabel="Voice"><p className="p-6" role="status">Loading…</p></DashboardLayout>;

  const field = 'w-full rounded border px-3 py-2';
  return (
    <DashboardLayout activeLabel="Voice">
      <div className="mx-auto max-w-3xl space-y-8 p-4 sm:p-6">
        <header>
          <h1 className="text-2xl font-semibold">Voice</h1>
          <p className="text-gray-600">A 60-second spoken brief each morning, and a phone line you can call to ask Vireek questions.</p>
        </header>

        <section className="space-y-4" aria-labelledby="brief-h">
          <h2 id="brief-h" className="text-xl font-medium">Morning brief</h2>
          <label className="flex items-center gap-2"><input type="checkbox" checked={prefs.brief_enabled} onChange={(e) => set('brief_enabled', e.target.checked)} /> Send me a spoken brief every morning</label>
          <div className="grid gap-4 sm:grid-cols-2">
            <label className="block text-sm">Send at<select className={field} value={prefs.send_hour} onChange={(e) => set('send_hour', Number(e.target.value))}>{HOURS.map((h) => <option key={h} value={h}>{hourLabel(h)}</option>)}</select></label>
            <label className="block text-sm">Language<select className={field} value={prefs.language} onChange={(e) => set('language', e.target.value as VoicePrefs['language'])}><option value="en">English</option><option value="es">Español</option><option value="fr">Français</option></select></label>
            <label className="block text-sm">No alerts from<select className={field} value={prefs.quiet_start} onChange={(e) => set('quiet_start', Number(e.target.value))}>{HOURS.map((h) => <option key={h} value={h}>{hourLabel(h)}</option>)}</select></label>
            <label className="block text-sm">until<select className={field} value={prefs.quiet_end} onChange={(e) => set('quiet_end', Number(e.target.value))}>{HOURS.map((h) => <option key={h} value={h}>{hourLabel(h)}</option>)}</select></label>
            <label className="block text-sm">Voice<select className={field} value={prefs.voice_choice} onChange={(e) => set('voice_choice', e.target.value as VoicePrefs['voice_choice'])}><option value="sarah">Sarah</option><option value="custom">My cloned voice (if ready)</option></select></label>
            <label className="block text-sm">Default playback speed<select className={field} value={prefs.speed} onChange={(e) => set('speed', Number(e.target.value))}>{SPEEDS.map((s) => <option key={s} value={s}>{s}×</option>)}</select></label>
            <label className="block text-sm">Daily voice budget (cents)<input type="number" min={0} max={5000} className={field} value={prefs.daily_cost_cap_cents} onChange={(e) => set('daily_cost_cap_cents', Math.min(5000, Math.max(0, Number(e.target.value) || 0)))} /></label>
          </div>
          <label className="flex items-center gap-2"><input type="checkbox" checked={prefs.skip_when_quiet} onChange={(e) => set('skip_when_quiet', e.target.checked)} /> Skip the brief when nothing notable happened</label>
          <fieldset className="space-y-2"><legend className="text-sm font-medium">Deliver by</legend>
            <label className="flex items-center gap-2"><input type="checkbox" checked={prefs.channel_in_app} onChange={(e) => set('channel_in_app', e.target.checked)} /> In-app player</label>
            <label className="flex items-center gap-2"><input type="checkbox" checked={prefs.channel_push} onChange={(e) => set('channel_push', e.target.checked)} /> Push notification (no numbers on the lock screen)</label>
            <label className="flex items-center gap-2"><input type="checkbox" checked={prefs.channel_email} onChange={(e) => set('channel_email', e.target.checked)} /> Email with transcript and audio link</label>
            <label className="flex items-center gap-2"><input type="checkbox" checked={prefs.channel_whatsapp} onChange={(e) => set('channel_whatsapp', e.target.checked)} /> WhatsApp voice message</label>
            {prefs.channel_whatsapp && <input aria-label="WhatsApp number" placeholder="+14155550123" className={field} value={prefs.whatsapp_number ?? ''} onChange={(e) => set('whatsapp_number', e.target.value)} />}
          </fieldset>
          <div className="flex flex-wrap gap-3">
            <button type="button" className="rounded bg-black px-4 py-2 text-white disabled:opacity-50" disabled={saving} onClick={() => void save()}>{saving ? 'Saving…' : 'Save changes'}</button>
            <button type="button" className="rounded border px-4 py-2 disabled:opacity-50" disabled={busy !== null}
              onClick={() => void run('sample', async () => setSampleUrl((await playSample(prefs.voice_choice, prefs.language)).audioUrl))}>{busy === 'sample' ? 'Loading…' : 'Play sample voice'}</button>
            <button type="button" className="rounded border px-4 py-2 disabled:opacity-50" disabled={busy !== null || (!prefs.brief_enabled && !brief)}
              onClick={() => void run('preview', async () => { setBrief(await previewBrief()); toast('Test brief ready', 'success'); })}>{busy === 'preview' ? 'Building…' : 'Test with today’s data'}</button>
          </div>
          <p className="text-xs text-gray-500">Save your settings before testing. Test briefs count toward your daily voice budget unless the same audio is already cached.</p>
          {sampleUrl && <audio src={sampleUrl} controls autoPlay className="w-full" aria-label="Sample voice" />}
          {brief?.brief ? <BriefPlayer brief={brief.brief} audioUrl={brief.audioUrl} defaultSpeed={prefs.speed} /> : <p className="text-sm text-gray-600">No brief yet. Turn it on and save, or use the test button.</p>}
        </section>

        <section className="space-y-4" aria-labelledby="call-h">
          <h2 id="call-h" className="text-xl font-medium">Call your Vireek</h2>
          <p className="text-sm text-gray-600">Call from a verified number, enter your PIN, then ask about yesterday, missed emergencies, who's on call or today's schedule. Dollar figures and texting a customer need an extra text-message code. Every request is logged.</p>
          <ul className="space-y-2">
            {numbers.map((n) => (
              <li key={n.id} className="flex items-center justify-between gap-2 rounded border p-3">
                <span className="min-w-0">{n.masked} {n.hasPin ? '' : '· PIN not set'} {n.locked ? '· locked' : ''}</span>
                <button type="button" className="text-sm underline" onClick={() => void run('rm', async () => { await removePhone(n.id); await refresh(); })}>Remove</button>
              </li>
            ))}
            {numbers.length === 0 && <li className="text-sm text-gray-600">No numbers yet.</li>}
          </ul>
          <div className="space-y-2 rounded border p-3">
            <label className="block text-sm">Phone number (with country code)<input className={field} inputMode="tel" placeholder="+14155550123" value={phone} onChange={(e) => setPhone(e.target.value)} /></label>
            {!codeSent ? (
              <button type="button" className="rounded border px-4 py-2 disabled:opacity-50" disabled={busy !== null || phone.length < 8}
                onClick={() => void run('code', async () => { await sendPhoneCode(phone); setCodeSent(true); toast('Code sent by text message', 'success'); })}>Text me a code</button>
            ) : (
              <>
                <label className="block text-sm">6-digit code<input className={field} inputMode="numeric" autoComplete="one-time-code" maxLength={6} value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))} /></label>
                <label className="block text-sm">Choose a 6-digit PIN<input className={field} type="password" inputMode="numeric" maxLength={6} value={pin} onChange={(e) => setPin(e.target.value.replace(/\D/g, ''))} /></label>
                <button type="button" className="rounded bg-black px-4 py-2 text-white disabled:opacity-50" disabled={busy !== null || code.length !== 6 || pin.length !== 6}
                  onClick={() => void run('enroll', async () => { await enrollPhone(phone, code, pin); toast('Number verified and PIN saved', 'success'); setCodeSent(false); setCode(''); setPin(''); setPhone(''); await refresh(); })}>Verify and save PIN</button>
              </>
            )}
          </div>
        </section>
      </div>
    </DashboardLayout>
  );
}
