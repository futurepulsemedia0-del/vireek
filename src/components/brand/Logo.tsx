import { type CSSProperties } from 'react';
import {
  LOGO_SHAPES,
  SYMBOL_DOT,
  WORDMARK_DOT,
  type LogoRole,
} from './logoPaths.generated';

/**
 * Vireek logo — inline SVG, outlined letterforms (no font dependency).
 *
 *   variant  wordmark | symbol | lockup (tile + wordmark) | stacked | tile
 *   size     rendered HEIGHT in px (width follows the artwork's aspect ratio,
 *            both attributes are set so the logo never causes layout shift)
 *   tone     auto  → indigo letters + orange accent, follows --accent-* tokens
 *                    (light/dark theme switch is automatic, no PNG pairs)
 *            mono  → everything currentColor (tile is knocked out)
 *            white → #fff
 *   animated subtle pulse on the orange dot (+ a soft ring on wordmark/symbol).
 *            Disabled under prefers-reduced-motion (see index.css).
 *
 * Use ONE logo per view. Geometry is generated by scripts/brand/build_brand.py.
 */
export type LogoVariant = 'wordmark' | 'symbol' | 'lockup' | 'stacked' | 'tile';
export type LogoTone = 'auto' | 'mono' | 'white';

export interface LogoProps {
  variant?: LogoVariant;
  size?: number;
  tone?: LogoTone;
  animated?: boolean;
  className?: string;
  /** Hide from assistive tech when the brand name is already announced next to the logo. */
  decorative?: boolean;
}

const DEFAULT_SIZE: Record<LogoVariant, number> = { wordmark: 28, symbol: 32, lockup: 40, stacked: 96, tile: 40 };

// Tiles are fixed-colour brand assets (like an app icon) and do not follow the theme.
const TILE_FILL: Record<string, string> = { tile: '#203AD8', tv: '#FFFFFF', td: '#FF8A5A' };

function fillFor(role: LogoRole, tone: LogoTone): string {
  if (tone === 'mono') return 'currentColor';
  if (tone === 'white') return '#FFFFFF';
  if (role === 'ink') return 'rgb(var(--accent-primary, 32 58 216))';
  if (role === 'acc') return 'rgb(var(--logo-accent, 193 79 38))';
  return TILE_FILL[role];
}

export function Logo({
  variant = 'wordmark',
  size,
  tone = 'auto',
  animated = false,
  className,
  decorative = false,
}: LogoProps) {
  const shape = LOGO_SHAPES[variant];
  const h = size ?? DEFAULT_SIZE[variant];
  const w = Math.round((h * shape.w * 10) / shape.h) / 10;
  const hasTile = variant === 'tile' || variant === 'lockup' || variant === 'stacked';
  const letters = variant === 'wordmark' || variant === 'symbol';
  // Mono/white: one merged path (tile knocked out). Animated letters-only variants keep layers so the dot can pulse.
  const useMono = tone !== 'auto' && (hasTile || !animated);
  const ring = animated && letters ? (variant === 'symbol' ? SYMBOL_DOT : WORDMARK_DOT) : null;
  const a11y = decorative
    ? ({ 'aria-hidden': true, focusable: 'false' } as const)
    : ({ role: 'img', 'aria-label': 'Vireek' } as const);
  const cls = ['vrk-logo', animated ? 'vrk-logo--animated' : '', className ?? ''].filter(Boolean).join(' ');
  const style: CSSProperties = { flex: 'none', overflow: animated ? 'visible' : undefined };

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={`0 0 ${shape.w} ${shape.h}`}
      width={w}
      height={h}
      className={cls}
      style={style}
      {...a11y}
    >
      {ring && (
        <circle
          className="vrk-logo-ring"
          cx={ring.cx}
          cy={ring.cy}
          r={ring.r}
          fill="none"
          stroke={fillFor('acc', tone)}
          strokeWidth={ring.r * 0.28}
        />
      )}
      {useMono ? (
        <path d={shape.mono} fill={tone === 'white' ? '#FFFFFF' : 'currentColor'} />
      ) : (
        shape.layers.map(([role, d], i) => (
          <path
            key={i}
            d={d}
            fill={fillFor(role, tone)}
            className={animated && (role === 'acc' || role === 'td') ? 'vrk-logo-dot' : undefined}
          />
        ))
      )}
    </svg>
  );
}

export default Logo;
